using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <see cref="GenerateEntityAnalysisResult"/>から、ECS SoAバックエンドの生成物
/// (<c>{Type}SoaGeneratedArchetype</c>マーカー構造体、<c>{Type}Store</c>のSoA実装、<c>{Type}ChunkView</c>)を
/// 生成する。実データの正本は<c>World</c>が共有する<c>ArchetypeStorage</c>のComponent列のみであり、
/// Facade(<c>{Type}</c>)は値を一切保持しない。正規化済みコンポーネント集合が同じ別のGenerateEntity型が
/// 既に行を持っていれば、同じ<c>ArchetypeStorage</c>(=同じChunk)を無償で共有する
/// (<c>World.GetOrCreateStorage</c>が<c>ArchetypeSignature</c>のType[]シーケンス一致だけで解決するため)。
/// </summary>
internal static class GenerateEntitySoaEmitter
{
    internal static void Emit(SourceProductionContext context, GenerateEntityAnalysisResult result)
    {
        string hintName = GenerateEntityEmitterSupport.BuildHintName(result, "Soa");
        string source = string.Join("\n", BuildSourceLines(result));
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    private static List<string> BuildSourceLines(GenerateEntityAnalysisResult result)
    {
        List<string> lines = ["// <auto-generated/>", "#nullable enable"];

        GenerateEntityEmitterSupport.OpenContainingScope(lines, result);

        AppendArchetypeMarker(lines, result);
        AppendStore(lines, result);
        AppendChunkView(lines, result);

        GenerateEntityEmitterSupport.CloseContainingScope(lines, result);
        lines.Add("");

        return lines;
    }

    private static void AppendArchetypeMarker(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string archetypeTypeName = $"{result.StructName}SoaGeneratedArchetype";

        lines.Add("");
        lines.Add($"internal struct {archetypeTypeName} : global::CSharpGameEngine.Ecs.IEcsArchetype<{archetypeTypeName}>");
        lines.Add("{");
        lines.Add("    public static global::System.Type[] ComponentTypes { get; } = new global::System.Type[]");
        lines.Add("    {");

        foreach (GenerateEntityComponentModel component in result.NormalizedComponents)
        {
            lines.Add($"        typeof({component.ComponentTypeFullyQualifiedName}),");
        }

        lines.Add("    };");
        lines.Add("");
        lines.Add("    public static global::CSharpGameEngine.Ecs.IComponentColumn[] CreateColumns()");
        lines.Add("    {");
        lines.Add("        return new global::CSharpGameEngine.Ecs.IComponentColumn[]");
        lines.Add("        {");

        foreach (GenerateEntityComponentModel component in result.NormalizedComponents)
        {
            lines.Add($"            new global::CSharpGameEngine.Ecs.ComponentColumn<{component.ComponentTypeFullyQualifiedName}>(),");
        }

        lines.Add("        };");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public static {archetypeTypeName} CreateView(global::CSharpGameEngine.Ecs.World world, global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        return default;");
        lines.Add("    }");
        lines.Add("}");
    }

    private static void AppendStore(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string structName = result.StructName;
        string archetypeTypeName = $"{structName}SoaGeneratedArchetype";

        lines.Add("");
        lines.Add($"public sealed class {structName}Store");
        lines.Add("{");
        lines.Add("    private readonly global::CSharpGameEngine.Ecs.World world;");
        lines.Add("");
        lines.Add($"    public {structName}Store(global::CSharpGameEngine.Ecs.World world)");
        lines.Add("    {");
        lines.Add("        this.world = world;");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public {structName} Create(in {structName}CreateInfo info)");
        lines.Add("    {");
        lines.Add($"        global::CSharpGameEngine.Ecs.Entity entity = this.world.CreateEntityCore<{archetypeTypeName}>();");
        lines.Add("");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add($"        this.world.GetComponentRef<{component.ComponentTypeFullyQualifiedName}>(entity, {component.NormalizedIndex}) = info.{component.PropertyName};");
        }

        lines.Add("");
        lines.Add($"        return new {structName}(this, entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public bool IsAlive(global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        return this.world.IsAlive(entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public void Destroy(global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        this.world.Destroy(entity);");
        lines.Add("    }");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add("");
            lines.Add($"    internal ref {component.ComponentTypeFullyQualifiedName} Get{component.PropertyName}Ref(global::CSharpGameEngine.Ecs.Entity entity)");
            lines.Add("    {");
            lines.Add($"        return ref this.world.GetComponentRef<{component.ComponentTypeFullyQualifiedName}>(entity, {component.NormalizedIndex});");
            lines.Add("    }");
        }

        lines.Add("");
        lines.Add($"    internal bool TryGetChunk(out {structName}ChunkView view)");
        lines.Add("    {");
        lines.Add($"        if (!this.world.TryGetArchetypeChunk<{archetypeTypeName}>(out global::CSharpGameEngine.Ecs.ArchetypeChunk chunk) || chunk.Count == 0)");
        lines.Add("        {");
        lines.Add("            view = default;");
        lines.Add("            return false;");
        lines.Add("        }");
        lines.Add("");
        lines.Add($"        view = new {structName}ChunkView(chunk);");
        lines.Add("        return true;");
        lines.Add("    }");
        lines.Add("}");
    }

    private static void AppendChunkView(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string structName = result.StructName;

        lines.Add("");
        lines.Add($"internal readonly ref struct {structName}ChunkView");
        lines.Add("{");
        lines.Add("    private readonly global::CSharpGameEngine.Ecs.ArchetypeChunk chunk;");
        lines.Add("");
        lines.Add($"    internal {structName}ChunkView(global::CSharpGameEngine.Ecs.ArchetypeChunk chunk)");
        lines.Add("    {");
        lines.Add("        this.chunk = chunk;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    internal int Count => this.chunk.Count;");
        lines.Add("");
        lines.Add("    internal global::System.ReadOnlySpan<global::CSharpGameEngine.Ecs.Entity> Entities => this.chunk.Entities;");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add("");
            lines.Add($"    internal global::System.Span<{component.ComponentTypeFullyQualifiedName}> {component.PropertyName} =>");
            lines.Add($"        this.chunk.GetColumnSpan<{component.ComponentTypeFullyQualifiedName}>({component.NormalizedIndex});");
        }

        lines.Add("}");
    }
}
