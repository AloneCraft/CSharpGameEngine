using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <see cref="GenerateEntityAnalysisResult"/>から、AoS(Array of Structs)バックエンドの生成物
/// (<c>{Type}AosGeneratedData</c>行構造体、<c>{Type}Store</c>のAoS実装、<c>{Type}ChunkView</c>)を生成する。
/// 実データの正本は<c>{Type}Store</c>が内包する<see cref="global::CSharpGameEngine.Ecs.AosEntityStore{TRow}"/>
/// のみであり、Facade(<c>{Type}</c>)は値を一切保持しない。
/// </summary>
internal static class GenerateEntityAosEmitter
{
    internal static void Emit(SourceProductionContext context, GenerateEntityAnalysisResult result)
    {
        string hintName = GenerateEntityEmitterSupport.BuildHintName(result, "Aos");
        string source = string.Join("\n", BuildSourceLines(result));
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    private static List<string> BuildSourceLines(GenerateEntityAnalysisResult result)
    {
        List<string> lines = ["// <auto-generated/>", "#nullable enable"];

        GenerateEntityEmitterSupport.OpenContainingScope(lines, result);

        AppendRowStruct(lines, result);
        AppendStore(lines, result);
        AppendChunkView(lines, result);

        GenerateEntityEmitterSupport.CloseContainingScope(lines, result);
        lines.Add("");

        return lines;
    }

    private static void AppendRowStruct(List<string> lines, GenerateEntityAnalysisResult result)
    {
        lines.Add("");
        lines.Add($"internal struct {result.StructName}AosGeneratedData");
        lines.Add("{");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add($"    internal {component.ComponentTypeFullyQualifiedName} {component.PropertyName};");
        }

        lines.Add("}");
    }

    private static void AppendStore(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string structName = result.StructName;
        string rowTypeName = $"{structName}AosGeneratedData";

        lines.Add("");
        lines.Add($"public sealed class {structName}Store");
        lines.Add("{");
        lines.Add($"    private readonly global::CSharpGameEngine.Ecs.AosEntityStore<{rowTypeName}> store = new();");
        lines.Add("");
        lines.Add("    public int Count => this.store.Count;");
        lines.Add("");
        lines.Add($"    public {structName} Create(in {structName}CreateInfo info)");
        lines.Add("    {");
        lines.Add($"        {rowTypeName} row = new {rowTypeName}");
        lines.Add("        {");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add($"            {component.PropertyName} = info.{component.PropertyName},");
        }

        lines.Add("        };");
        lines.Add("");
        lines.Add("        global::CSharpGameEngine.Ecs.Entity entity = this.store.Create(in row);");
        lines.Add($"        return new {structName}(this, entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public bool IsAlive(global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        return this.store.IsAlive(entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public void Destroy(global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        this.store.Destroy(entity);");
        lines.Add("    }");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add("");
            lines.Add($"    internal ref {component.ComponentTypeFullyQualifiedName} Get{component.PropertyName}Ref(global::CSharpGameEngine.Ecs.Entity entity)");
            lines.Add("    {");
            lines.Add($"        return ref this.store.GetRowRef(entity).{component.PropertyName};");
            lines.Add("    }");
        }

        lines.Add("");
        lines.Add($"    internal bool TryGetChunk(out {structName}ChunkView view)");
        lines.Add("    {");
        lines.Add("        if (this.store.Count == 0)");
        lines.Add("        {");
        lines.Add("            view = default;");
        lines.Add("            return false;");
        lines.Add("        }");
        lines.Add("");
        lines.Add($"        view = new {structName}ChunkView(this.store.AsEntitiesSpan(), this.store.AsRowsSpan());");
        lines.Add("        return true;");
        lines.Add("    }");
        lines.Add("}");
    }

    private static void AppendChunkView(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string structName = result.StructName;
        string rowTypeName = $"{structName}AosGeneratedData";

        lines.Add("");
        lines.Add($"internal readonly ref struct {structName}ChunkView");
        lines.Add("{");
        lines.Add($"    internal {structName}ChunkView(global::System.ReadOnlySpan<global::CSharpGameEngine.Ecs.Entity> entities, global::System.Span<{rowTypeName}> rows)");
        lines.Add("    {");
        lines.Add("        this.Entities = entities;");
        lines.Add("        this.Rows = rows;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    internal int Count => this.Rows.Length;");
        lines.Add("");
        lines.Add("    internal global::System.ReadOnlySpan<global::CSharpGameEngine.Ecs.Entity> Entities { get; }");
        lines.Add("");
        lines.Add($"    internal global::System.Span<{rowTypeName}> Rows {{ get; }}");
        lines.Add("}");
    }
}
