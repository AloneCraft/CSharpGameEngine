using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>IScene</c>実装クラスへ、Scene DSLから直接導いた<c>Instantiate</c>を追加生成する(ADR-0040)。
///
/// <para>
/// <b>生成コードに<c>Node</c>も<c>object[]</c>も<c>IScene</c>も現れない。</b>Runtimeで
/// 「Nodeオブジェクトグラフを作る → <c>object[]</c>を走査する → Component型を判定する → AddComponentする」
/// という処理は一切行わず、コンパイル時に確定したComponent構成から<c>ArchetypeNN.Create</c>を直接呼ぶ。
/// Scene authoringの抽象はRuntimeのホットパスから完全に消える。
/// </para>
///
/// <para>
/// あわせて<c>private</c>コンストラクターを出す。Scene定義はRuntime instanceではないので
/// <c>new MainScene()</c>は成立してはならず、これで外部からの構築をコンパイルエラーにする
/// (ユーザーが自分でコンストラクターを書いていた場合はSCENE102で弾かれる)。
/// </para>
/// </summary>
internal static class SceneInstantiateEmitter {
    private const string EntityFullyQualifiedName="global::CSharpGameEngine.Entities.Entity";
    private const string WorldFullyQualifiedName="global::CSharpGameEngine.Entities.World";
    private const string SceneInstanceFullyQualifiedName="global::CSharpGameEngine.Entities.SceneInstance";
    private const string SceneDefinitionInterfaceFullyQualifiedName="global::CSharpGameEngine.Entities.ISceneDefinition";
    internal const string ParentFullyQualifiedName="global::CSharpGameEngine.Entities.Parent";
    internal const string SceneNodeTagFullyQualifiedName="global::CSharpGameEngine.Entities.SceneNodeTag";

    internal static void Emit(SourceProductionContext Context,SceneEmitModel Scene,GameSystemRegistry Registry){
        if(!Scene.CanEmit||Scene.Root is not { } Root){
            return;
        }

        Dictionary<string,int>ComponentIndexByType=new(StringComparer.Ordinal);

        foreach(GameSystemComponentInfo Component in Registry.ComponentsByIndex){
            ComponentIndexByType[Component.TypeFullyQualifiedName]=Component.Index;
        }

        List<string>Lines=["// <auto-generated/>","#nullable enable"];

        if(Scene.Namespace is not null){
            Lines.Add($"namespace {Scene.Namespace};");
        }

        Lines.Add($"partial class {Scene.ClassName} : {SceneDefinitionInterfaceFullyQualifiedName} {{");
        Lines.Add("    /// <summary>Scene定義はRuntime instanceではないため、外部から構築できないようにする(ADR-0040)。</summary>");
        Lines.Add($"    private {Scene.ClassName}() {{");
        Lines.Add("    }");
        Lines.Add("    /// <summary>このSceneが生成するEntityの総数。</summary>");
        Lines.Add($"    public const int SceneEntityCount = {Scene.TotalNodeCount};");
        Lines.Add($"    public static {SceneInstanceFullyQualifiedName} Instantiate(ref {WorldFullyQualifiedName} World) {{");
        Lines.Add($"        {SceneInstanceFullyQualifiedName} Instance = World.BeginSceneInstance();");

        EmitNode(Lines,Root,ParentLocalName:null,Registry,ComponentIndexByType);

        Lines.Add($"        World.EndSceneInstance(Instance, {Root.LocalName});");
        Lines.Add("        return Instance;");
        Lines.Add("    }");
        Lines.Add($"    static {SceneInstanceFullyQualifiedName} {SceneDefinitionInterfaceFullyQualifiedName}.Instantiate(ref {WorldFullyQualifiedName} World) {{");
        Lines.Add("        return Instantiate(ref World);");
        Lines.Add("    }");
        Lines.Add("}");
        Lines.Add("");

        var HintName=Scene.Namespace is null
            ? $"{Scene.ClassName}.Scene.g.cs"
            : $"{Scene.Namespace}.{Scene.ClassName}.Scene.g.cs";

        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }

    /// <summary>
    /// 1ノードの実効Component構成を、宣言順 → 0個なら<c>SceneNodeTag</c> → 非Rootは末尾に<c>Parent</c>、
    /// という固定順で返す。
    ///
    /// <para>
    /// <b>Archetypeの登録(<see cref="SceneComponentSetCollector"/>)と生成(<see cref="EmitNode"/>)が
    /// 必ず同じ集合を導出するよう、両者からこの1箇所を共有する。</b>ズレると「Archetypeが見つからない」
    /// という診断困難なビルド破壊になる。
    /// </para>
    /// </summary>
    internal static List<(string TypeFullyQualifiedName,string?EmitExpressionText)>BuildEffectiveComponents(SceneEmitNode Node,string?ParentLocalName){
        List<(string,string?)>Components=[];

        if(Node.Components.Length==0){
            // Archetypeは最低1つのComponentを要求する。
            Components.Add((SceneNodeTagFullyQualifiedName,null));
        } else {
            foreach(SceneEmitComponent Component in Node.Components){
                Components.Add((Component.TypeFullyQualifiedName,Component.EmitExpressionText));
            }
        }

        if(ParentLocalName is not null){
            Components.Add((ParentFullyQualifiedName, $"new {ParentFullyQualifiedName} {{ Value = {ParentLocalName} }}"));
        }

        return Components;
    }

    private static void EmitNode(
        List<string>Lines,
        SceneEmitNode Node,
        string?ParentLocalName,
        GameSystemRegistry Registry,
        Dictionary<string,int>ComponentIndexByType){
        List<(string TypeFullyQualifiedName,string?EmitExpressionText)>Components=BuildEffectiveComponents(Node,ParentLocalName);
        var NameComment=Node.Name is null?"(unnamed)": $"\"{Node.Name}\"";
        Lines.Add($"        // [{Node.PathDisplay}] {NameComment}");

        GameSystemArchetypeInfo?Archetype=Registry.FindArchetype([.. Components.Select(C=>ComponentIndexByType[C.TypeFullyQualifiedName])]);

        if(Archetype is not { } ArchetypeInfo){
            // SceneComponentSetCollectorがScene形状も登録しているため、通常ここには到達しない。
            Lines.Add($"        // ERROR: no archetype registered for node '{Node.PathDisplay}'");
            return;
        }

        // Createのパラメータ順はArchetypeの宣言順なので、初期化式もその順へ並べ替える。
        Dictionary<int,string?>ExpressionByIndex=[];

        foreach((var TypeFqn,var Expression)in Components){
            ExpressionByIndex[ComponentIndexByType[TypeFqn]]=Expression;
        }

        var Arguments=string.Join(", ",ArchetypeInfo.ComponentIndices.Select(I=>ExpressionByIndex[I]??"default"));
        Lines.Add($"        {EntityFullyQualifiedName} {Node.LocalName} = World.AttachToScene(Instance, global::CSharpGameEngine.Entities.{ArchetypeInfo.Name}.Create(ref World, {Arguments}));");

        foreach(SceneEmitNode Child in Node.Children){
            EmitNode(Lines,Child,Node.LocalName,Registry,ComponentIndexByType);
        }
    }
}
