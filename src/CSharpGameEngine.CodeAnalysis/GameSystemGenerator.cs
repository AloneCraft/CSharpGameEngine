using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using CSharpGameEngine.SceneAnalysis.Json;
using CSharpGameEngine.SceneAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>ISystem</c>を実装するstructとシーン JSON(<c>Scenes\**\*.json</c>、ADR-0070)から、閉じた集合として列挙される
/// Archetype群・<c>World</c>の構造変更API・メインループ・Sceneの<c>Instantiate</c>、そして条件を満たす
/// 場合はエントリポイントまで生成する(ADR-0033/ADR-0070、エントリポイントは
/// <see cref="GameSystemEntryPointEmitter"/>)。
///
/// <para>
/// Systemはマーカー属性を持たない(役割は引数の形から構造的に推論する。Phaseや順序だけは
/// <c>[SystemPhase]</c>/<c>[SystemOrder]</c>などの属性で受け取る)ため、System検出には
/// <c>ForAttributeWithMetadataName</c>が使えず、<c>CreateSyntaxProvider</c>でbase listを持つ型宣言を
/// 拾って意味解析で<c>ISystem</c>実装を確認する(struct限定にすると「classで書いてしまった」という
/// SYSGEN001自体が到達不能になるため、あえてstruct限定にしない)。<c>Update</c>は<c>void</c>が標準(ADR-0072)。
/// シーンはC#のクラスではなく、AdditionalFilesのシーン JSONから読む。
/// </para>
///
/// <para>
/// シーンがこのGeneratorへ統合されているのは必然的な設計判断である: Sceneのノード形状とSystemの
/// Update/Spawn形状は<b>同一のArchetype空間</b>に入る必要があり(両方が単一の<c>partial struct World</c>/
/// <c>enum Archetype</c>を作るため、生成は1回しか行えない)、2つのGeneratorが独立に同じレジストリを
/// 再導出する案はズレたときに「型が見つからない」という診断困難なビルド破壊になる。
/// </para>
///
/// <para>
/// <b>シーンの診断はここでは報告しない。</b>シーン JSON の診断(SCENE2xx)は<see cref="SceneJsonDslAnalyzer"/>が、
/// C#のシーンクラスが残っていないかの検査(SCENE206)は<see cref="SceneDslAnalyzer"/>が報告し、
/// このGeneratorは同じ解析結果を生成可否の判定にしか使わない(二重スクイグルの防止)。
/// </para>
///
/// <para>
/// 出力は<c>ISystem</c>型がコンパイル内に実在する場合に限る。<c>CSharpGameEngine.CodeAnalysis</c>は
/// 1つのアナライザーパッケージに複数のGeneratorを同居させる規約(ADR-0014)のため、このECSを使う意図が
/// 無いプロジェクトでも参照だけで本Generatorが走ってしまい、無条件出力すると
/// <c>CSharpGameEngine.Entities</c>名前空間に空の<c>World</c>等が紛れ込んで実際にビルドを壊す
/// (ADR-0032実装時に確認済みの回帰)。
/// </para>
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class GameSystemGenerator:IIncrementalGenerator {
    public void Initialize(IncrementalGeneratorInitializationContext Context){
        var Candidates=Context.SyntaxProvider.CreateSyntaxProvider(
                                                                  static(Node,_)=>Node is TypeDeclarationSyntax { BaseList.Types.Count:>0 },
                                                                  static(Ctx,_)=>TryAnalyzeSystem(Ctx));

        var Systems=Candidates
                  .Where(static Result=>Result.HasValue)
                  .Select(static(Result,_)=>Result!.Value);

        // ADR-0070：シーンは Scenes\**\*.json の AdditionalFiles (SceneFiles)。C# のシーンクラスはビルドしない (SCENE206)。
        // それらの診断は SceneJsonDslAnalyzer が担当する。ここでは出力するかどうかだけを判断する。
        // シンボルに依存しない SceneEmitModels だけを後段へ渡す (SceneModelBridge を参照)。
        var JsonSceneDeclarations=Context.AdditionalTextsProvider
                                         .Combine(Context.AnalyzerConfigOptionsProvider)
                                         .Where(static Pair=>SceneJsonDslAnalyzer.IsSceneFile(Pair.Left.Path,Pair.Right.GlobalOptions))
                                         .Select(static(Pair,_)=>Pair.Left)
                                         .Combine(Context.CompilationProvider)
                                         .Select(static(Pair,Ct)=>SceneModelBridge.TryAnalyzeJson(Pair.Left,Pair.Right,Ct))
                                         .Where(static Result=>Result.HasValue)
                                         .Select(static(Result,_)=>Result!.Value);
        // ADR-0070：プロジェクト単位のシーン JSON Schema を定数として埋め込み、ビルドが
        // .cge/scene.schema.json に書き出す。VS の JSON エディターが未定義の型やメンバーに警告するために使う。
        var SceneSchema=Context.CompilationProvider.Select(static(Compilation,_)=>
            Compilation.GetTypeByMetadataName(SceneDslWellKnownNames.SceneInterfaceMetadataName) is null
                ?null
                :SceneJsonSchemaBuilder.Build(Compilation));
        Context.RegisterSourceOutput(SceneSchema,static(Spc,Schema)=>{
            if(Schema is null){ return; }
            Spc.AddSource("GameSystem.SceneSchema.g.cs",
                "// <auto-generated/>\n"
                +"namespace CSharpGameEngine.Generated;\n"
                +"/// <summary>The project's scene JSON Schema (ADR-0070); the build writes it to .cge/scene.schema.json.</summary>\n"
                +"internal static class CgeGeneratedSceneSchema {\n"
                +"    internal const string Json = "+Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(Schema,quote:true)+";\n"
                +"}\n");
        });
        var AllSceneDeclarations=JsonSceneDeclarations.Collect();

        // IRuntimeComponent<TAuthored>の実装。作者Componentに随伴して自動付与する対応表を作るために
        // 拾う。ISystem/IScene と同じく属性が無いのでForAttributeWithMetadataNameは使えず、
        // base listを持つstruct宣言を安価に絞ってから意味解析で確認する。流れるのは文字列ペアだけ。
        var RuntimeComponentPairs=Context.SyntaxProvider.CreateSyntaxProvider(
                                                                             static(Node,_)=>SceneRuntimeComponentCollector.IsCandidate(Node),
                                                                             static(Ctx,_)=>SceneRuntimeComponentCollector.TryAnalyze(Ctx))
                                       .Where(static Result=>Result.HasValue)
                                       .Select(static(Result,_)=>Result!.Value);

        // ADR-0077 ステージ 7：型付きアセットカタログ (Assets.Sounds.Jump) と、シーンが実在するアセットファイルを指定しているかの検査。
        var AssetPaths=Context.AdditionalTextsProvider
                              .Combine(Context.AnalyzerConfigOptionsProvider)
                              .Select(static(Pair,_)=>{
                                  return AssetCatalogEmitter.RelativeAssetPath(Pair.Left.Path,SceneJsonDslAnalyzer.ProjectDirectoryOf(Pair.Right.GlobalOptions),SceneJsonDslAnalyzer.PluginRootsOf(Pair.Right.GlobalOptions));
                              })
                              .Where(static Path=>Path is not null)
                              .Select(static(Path,_)=>Path!)
                              .Collect();
        var SceneTexts=Context.AdditionalTextsProvider
                              .Combine(Context.AnalyzerConfigOptionsProvider)
                              .Where(static Pair=>SceneJsonDslAnalyzer.IsSceneFile(Pair.Left.Path,Pair.Right.GlobalOptions))
                              .Select(static(Pair,Ct)=>(Pair.Left.Path,Text:Pair.Left.GetText(Ct)))
                              .Where(static Pair=>Pair.Text is not null)
                              .Select(static(Pair,_)=>(Pair.Path,Text:Pair.Text!))
                              .Collect();
        // ADR-0079：データアセット (*.cgeasset) もカタログのメンバーであり、その JSON 値はシーンコンポーネントと同様にコンパイルされる。
        var DataAssets=Context.AdditionalTextsProvider
                              .Combine(Context.AnalyzerConfigOptionsProvider)
                              .Select(static(Pair,_)=>{
                                  return (File:Pair.Left,Path:AssetCatalogEmitter.RelativeAssetPath(Pair.Left.Path,SceneJsonDslAnalyzer.ProjectDirectoryOf(Pair.Right.GlobalOptions),SceneJsonDslAnalyzer.PluginRootsOf(Pair.Right.GlobalOptions)));
                              })
                              .Where(static Pair=>Pair.Path is not null&&Pair.Path.EndsWith(AssetCatalogEmitter.DataAssetExtension,StringComparison.OrdinalIgnoreCase))
                              .Combine(Context.CompilationProvider)
                              .Select(static(Pair,Ct)=>AssetCatalogEmitter.AnalyzeDataAsset(Pair.Left.File,Pair.Left.Path,Pair.Right,Ct))
                              .Where(static Model=>Model.HasValue)
                              .Select(static(Model,_)=>Model!.Value)
                              .Collect();
        var ImageMetadata=Context.AdditionalTextsProvider.Combine(Context.AnalyzerConfigOptionsProvider)
            .Where(static Pair=>Pair.Left.Path.EndsWith(".meta",StringComparison.OrdinalIgnoreCase))
            .Select(static(Pair,Ct)=>(Path:AssetCatalogEmitter.RelativeAssetPath(Pair.Left.Path.Substring(0,Pair.Left.Path.Length-5),SceneJsonDslAnalyzer.ProjectDirectoryOf(Pair.Right.GlobalOptions),SceneJsonDslAnalyzer.PluginRootsOf(Pair.Right.GlobalOptions)),Json:Pair.Left.GetText(Ct)?.ToString()))
            .Where(static Pair=>Pair.Path is not null&&Pair.Json is not null)
            .Select(static(Pair,_)=>(Pair.Path!,Pair.Json!)).Collect();
        var RuntimeGate=Context.CompilationProvider.Select(static(Compilation,Ct)=>GenerationGate.FromCompilation(Compilation,Ct));
        Context.RegisterSourceOutput(AssetPaths.Combine(DataAssets).Combine(ImageMetadata).Combine(RuntimeGate),static(Spc,Data)=>{
            if(Data.Right.HasRuntimeMarker){ AssetCatalogEmitter.Emit(Spc,Data.Left.Left.Left,Data.Left.Left.Right,Data.Left.Right); }
        });
        Context.RegisterSourceOutput(AssetPaths.Combine(SceneTexts).Combine(RuntimeGate),static(Spc,Data)=>{
            if(Data.Right.HasRuntimeMarker){ AssetCatalogEmitter.ReportMissing(Spc,Data.Left.Left,Data.Left.Right); }
        });

        // ADR-0077 ステージ 4：[InputActions] 構造体を入力マップとフレームごとの Read に変換する。
        var InputActionOutputs=Context.SyntaxProvider.ForAttributeWithMetadataName(
                                                                              InputActionsEmitter.AttributeMetadataName,
                                                                              static(Node,_)=>Node is TypeDeclarationSyntax,
                                                                              static(Ctx,Ct)=>InputActionsEmitter.Transform(Ctx,Ct))
                                       .Collect();
        Context.RegisterSourceOutput(InputActionOutputs,static(Spc,Outputs)=>InputActionsEmitter.Emit(Spc,Outputs));

        Context.RegisterSourceOutput(Systems,static(Spc,Result)=>GameSystemDiagnostics.ReportAll(Spc,Result));

        // Compilationそのものをキャッシュキーに含めると、キーストロークのたびに重い生成段が丸ごと
        // 再実行されてしまう。生成可否の判定に必要な事実だけを小さな比較可能値へ縮約する(ADR-0040)。
        var Gate=Context.CompilationProvider.Select(
                                                   static(Compilation,Ct)=>GenerationGate.FromCompilation(Compilation,Ct));

        IncrementalValueProvider<((ImmutableArray<GameSystemResult>Systems,ImmutableArray<SceneEmitModel>SceneDeclarations,ImmutableArray<SceneRuntimeComponentPair>RuntimeComponentPairs)Sources,GenerationGate Gate)>Combined=
            Systems.Collect()
                .Combine(AllSceneDeclarations)
                .Combine(RuntimeComponentPairs.Collect())
                .Select(static(Data,_)=>(Data.Left.Left,Data.Left.Right,Data.Right))
                .Combine(Gate);

        Context.RegisterSourceOutput(Combined,static(Spc,Source)=>{
            if(!Source.Gate.HasRuntimeMarker){
                return;
            }

            var SystemResults=Source.Sources.Systems;

            // ADR-0040のScene DSL。Collect()の順序に依存しないよう必ず整列してから使う
            // (決定論性テストが両方の実行で同じ出力になることを要求している)。
            List<SceneEmitModel>ValidSceneDeclarations=[.. Source.Sources.SceneDeclarations.Where(static S=>S.CanEmit)];
            ValidSceneDeclarations.Sort(static(A,B)=>{
                var ByFile=string.CompareOrdinal(A.FilePath,B.FilePath);
                return ByFile!=0?ByFile:A.DeclarationPosition.CompareTo(B.DeclarationPosition);
            });
            // シーンファイル 2 つで同じクラスを宣言する（ファイルをコピーした場合など）ときは、パス順で最初のものだけをビルドする。
            // 後から出現するファイルには SceneJsonDslAnalyzer が SCENE207 を報告する。同じシーンを 2 回追加するとヒント名が重複して例外になり、
            // ジェネレーターの出力全体が失われていた。
            HashSet<string>BuiltScenes=new(StringComparer.Ordinal);
            ValidSceneDeclarations.RemoveAll(Scene=>!BuiltScenes.Add(Scene.ClassFullyQualifiedName));

            // 起動シーンは「クエリ{Bootstrap}を持つ合成System」として、実際に検出されたSystemと同じモデル・同じ
            // 実行順序(GameSystemExecutionOrder)へ合流する(理由はSceneStartupSystemEmitterのXMLコメント参照)。
            // 合成SystemはstartupOrderを持ち、FrameInputの先頭に並ぶ(ADR-0073決定事項4)。
            List<GameSystemResult>ValidStartupSystems=[];

            foreach(var StartupScene in ValidSceneDeclarations.Where(static S=>S.IsStartupScene)){
                ValidStartupSystems.Add(SceneStartupSystemEmitter.BuildSyntheticSystemResult(StartupScene));
            }

            ImmutableArray<GameSystemResult>AllSystemResults=[.. SystemResults,.. ValidStartupSystems];

            // ADR-0077 ステージ 6：イベント受信側は、イベントを送信するシステムからフェーズと順序を引き継ぐ。
            List<Diagnostic>WiringDiagnostics=[];
            AllSystemResults=GameSystemEventWiring.Apply(AllSystemResults,WiringDiagnostics);
            foreach(var WiringDiagnostic in WiringDiagnostics){
                Spc.ReportDiagnostic(WiringDiagnostic);
            }

            foreach(var OrderDiagnostic in GameSystemExecutionOrder.Validate(AllSystemResults)){
                Spc.ReportDiagnostic(OrderDiagnostic);
            }

            // 随伴付与の索引。ArchetypeのCollectとEmitが必ず同じ集合を導出するよう、以降の両方へ
            // 同じインスタンスを渡す(引数なので渡し忘れはコンパイルエラーになる)。
            var RuntimeComponents=SceneRuntimeComponentMap.Build(
                Source.Sources.RuntimeComponentPairs,out var RuntimeComponentDiagnostics);

            foreach(var RuntimeComponentDiagnostic in RuntimeComponentDiagnostics){
                Spc.ReportDiagnostic(RuntimeComponentDiagnostic);
            }
            List<IReadOnlyList<string>>AdditionalComponentSets=[];

            foreach(var SceneDeclaration in ValidSceneDeclarations){
                AdditionalComponentSets.AddRange(SceneComponentSetCollector.Collect(SceneDeclaration,RuntimeComponents));
            }

            // エントリポイントを出すかどうかはレジストリ構築の前に決める。生成する場合にだけ
            // Bootstrapの形状を登録し、出さないコンパイルへ余計なArchetypeが増えないようにする。
            var EntryPointPlan=
                GameSystemEntryPointEmitter.ShouldEmitPlan(Source.Gate,AllSystemResults);

            if(EntryPointPlan.Diagnostic is { } EntryPointDiagnostic){
                Spc.ReportDiagnostic(EntryPointDiagnostic);
            }

            if(EntryPointPlan.Emit){
                AdditionalComponentSets.Add([GameSystemEntryPointEmitter.BootstrapComponentFullyQualifiedName]);
            }

            var Registry=GameSystemIndexAssigner.Assign(AllSystemResults,AdditionalComponentSets);

            foreach(var Diagnostic in Registry.Diagnostics){
                Spc.ReportDiagnostic(Diagnostic);
            }

            var Schedule=GameSystemScheduleAnalyzer.Build(Registry);
            foreach(var Diagnostic in Schedule.Diagnostics){
                Spc.ReportDiagnostic(Diagnostic);
            }

            GameSystemTypesEmitter.Emit(Spc,Registry);
            GameSystemWorldEmitter.Emit(Spc,Registry);
            GameSystemSnapshotEmitter.Emit(Spc,Registry);
            SpatialWorldEmitter.Emit(Spc,Registry);
            GameSystemLoopEmitter.Emit(Spc,Registry);
            GameSystemScheduleEmitter.Emit(Spc,Schedule);
            GeneratedEditorPreviewBridgeEmitter.Emit(Spc,ValidSceneDeclarations,Registry);
            GeneratedSceneBakeHostEmitter.Emit(Spc,ValidSceneDeclarations,Registry,Source.Gate);
            if(Source.Gate.HasWorldCellActivationContract){
                GeneratedWorldCellActivationSinkEmitter.Emit(Spc,ValidSceneDeclarations);
            }

            if(EntryPointPlan.Emit){
                GameSystemEntryPointEmitter.Emit(Spc,Registry);
            }

            foreach(var SceneDeclaration in ValidSceneDeclarations){
                SceneInstantiateEmitter.Emit(Spc,SceneDeclaration,Registry,RuntimeComponents,Source.Gate.HasSceneSpawnContract);

                if(SceneDeclaration.IsStartupScene){
                    SceneStartupSystemEmitter.EmitHiddenSystem(Spc,SceneDeclaration);
                }
            }
        });
    }

    private static GameSystemResult?TryAnalyzeSystem(GeneratorSyntaxContext Ctx){
        if(Ctx.SemanticModel.GetDeclaredSymbol(Ctx.Node)is not INamedTypeSymbol Symbol){
            return null;
        }

        if(Symbol.TypeKind==TypeKind.Interface){ return null; }

        var ImplementsISystem=Symbol.AllInterfaces.Any(static I=>
            I.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)==GameSystemAnalyzer.SystemInterfaceFullyQualifiedName);

        return ImplementsISystem?GameSystemAnalyzer.Analyze(Symbol):null;
    }
}
