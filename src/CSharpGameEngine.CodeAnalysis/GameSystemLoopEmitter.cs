using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>Emits the persistent, system-major fixed-phase ECS loop.</summary>
internal static class GameSystemLoopEmitter {
    private const string HintName="GameSystem.Loop.g.cs";

    internal static bool HasDispatchSystem(IEnumerable<GameSystemResult> Systems)=>
        Systems.Any(static System=>System.Diagnostics.Length==0&&System.Methods.Any(static Method=>Method.Role==GameSystemMethodRole.Dispatch));

    internal static void Emit(SourceProductionContext Context,GameSystemRegistry Registry){
        List<GameSystemResult> DispatchSystems=[.. Registry.ValidSystems.Where(static System=>System.Methods.Any(static Method=>Method.Role==GameSystemMethodRole.Dispatch))];
        List<GameSystemResult> AllSystems=[.. Registry.ValidSystems.Where(static System=>System.Methods.Any(static Method=>Method.Role is GameSystemMethodRole.Dispatch or GameSystemMethodRole.Shutdown))];
        if(Registry.Archetypes.Length==0||DispatchSystems.Count==0){ return; }

        Dictionary<string,int> ComponentIndexByType=new(StringComparer.Ordinal);
        Dictionary<string,string> FieldNameByComponentFqn=new(StringComparer.Ordinal);
        foreach(GameSystemComponentInfo Component in Registry.ComponentsByIndex){
            ComponentIndexByType[Component.TypeFullyQualifiedName]=Component.Index;
            FieldNameByComponentFqn[Component.TypeFullyQualifiedName]=Component.FieldName;
        }

        List<SystemBinding> Systems=BuildSystemBindings(AllSystems);
        List<ContextBinding> Contexts=BuildContextBindings(AllSystems);
        bool HasEngineHost=Contexts.Any(static Context=>Context.TypeFullyQualifiedName=="global::CSharpGameEngine.Runtime.Windows.EngineHost");
        Dictionary<string,string> ContextNameByFqn=Contexts.ToDictionary(static Binding=>Binding.TypeFullyQualifiedName,static Binding=>Binding.ParameterName,StringComparer.Ordinal);

        List<string> Lines=[
            "// <auto-generated/>",
            "#nullable enable",
            "namespace CSharpGameEngine.Generated;",
            "internal struct GeneratedSystemSet {",
        ];
        foreach(SystemBinding System in Systems){
            Lines.Add($"    internal {System.TypeReference} {System.VariableName};");
        }
        Lines.Add("}");
        Lines.Add("internal static class GeneratedGameLoop {");
        Lines.Add($"    private static void RunSimulationTick({BuildSimulationTickParameterList(Contexts)}) {{");
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.FixedSimulation, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, EditorOnly, RealtimeOnly);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.PhysicsSimulation, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, EditorOnly, RealtimeOnly);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.PostPhysics, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, EditorOnly, RealtimeOnly);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add("        if (State.Enabled) State.SetSimulationTiming(checked(State.FixedTick + 1UL), State.FixedTickRate, global::CSharpGameEngine.Entities.SystemPhase.FixedSimulation);");
        Lines.Add("    }");
        Lines.Add($"    internal static void RunBakeTick(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
        Lines.Add("        if (!State.Enabled) return;");
        Lines.Add($"        RunSimulationTick(ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, false, false);");
        if(SpatialWorldEmitter.ShouldEmit(Registry)){ Lines.Add("        if (State.Enabled) State.World.RefreshGlobalSpatialIndex();"); }
        Lines.Add("    }");
        Lines.Add($"    internal static void RunFrame({BuildSystemSetFrameParameterList(Contexts)}) {{");
        Lines.Add("        if (!State.Enabled) return;");
        Lines.Add("        State.SetFrameDelta(ElapsedCounter, CounterFrequency);");
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.FrameInput, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, false, false);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add("        if (!State.Enabled) return;");
        Lines.Add("        var Steps = 0;");
        Lines.Add("        if (State.PlaybackState == global::CSharpGameEngine.Entities.SimulationPlaybackState.Running) {");
        Lines.Add("            var Advance = Scheduler.Advance(ElapsedCounter, CounterFrequency);");
        Lines.Add("            Steps = Advance.Steps;");
        Lines.Add("            State.InterpolationAlpha = Advance.InterpolationAlpha;");
        Lines.Add("            if (Advance.ShouldReportOverrun) {");
        Lines.Add("                global::System.Console.Error.WriteLine("+(char)34+"CGE-FIXED-TICK-OVERRUN attemptedSteps="+(char)34+" + Advance.AttemptedSteps + "+(char)34+" maximumSteps="+(char)34+" + Scheduler.MaximumStepsPerFrame + "+(char)34+" backlog="+(char)34+" + Advance.BacklogSteps + "+(char)34+" policy="+(char)34+" + Advance.OverrunPolicy);");
        Lines.Add("            }");
        Lines.Add("        } else {");
        Lines.Add("            State.InterpolationAlpha = Scheduler.InterpolationAlpha;");
        Lines.Add("            if (State.TryConsumeSimulationStep()) Steps = 1;");
        Lines.Add("        }");
        Lines.Add("        for (var StepIndex = 0; StepIndex < Steps; StepIndex++) {");
        Lines.Add($"            RunSimulationTick(ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, false, false);");
        Lines.Add("            if (!State.Enabled) return;");
        Lines.Add("        }");
        if(SpatialWorldEmitter.ShouldEmit(Registry)){ Lines.Add("        State.World.RefreshGlobalSpatialIndex();"); }
        Lines.Add("        if (!State.Enabled) return;");
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.Presentation, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, false, false);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add("    }");

        // Compatibility overload for callers generated before GeneratedSystemSet. Runtime and editor paths do not use it.
        Lines.Add($"    internal static void RunFrame({BuildLegacyFrameParameterList(Systems,Contexts)}) {{");
        Lines.Add("        GeneratedSystemSet Systems = default;");
        foreach(SystemBinding System in Systems){ Lines.Add($"        Systems.{System.VariableName} = {System.VariableName};"); }
        Lines.Add($"        RunFrame(ref State, ref Systems, ref Scheduler, ElapsedCounter, CounterFrequency{BuildContextArgumentSuffix(Contexts)});");
        foreach(SystemBinding System in Systems){ Lines.Add($"        {System.VariableName} = Systems.{System.VariableName};"); }
        Lines.Add("    }");

        Lines.Add($"    private static void RunPhase(global::CSharpGameEngine.Entities.SystemPhase Phase, {BuildPhaseParameterList(Contexts)}) {{");
        Lines.Add("        State.SetSimulationTiming(State.FixedTick, State.FixedTickRate, Phase);");
        Lines.Add("        State.World.BeginSystemExecution();");
        Lines.Add("        try {");
        foreach(SystemBinding Binding in Systems){
            bool IsEditor=Binding.System.ExecuteInEditor;
            bool IsRealtime=Binding.System.RealtimeInEditor;
            Lines.Add($"        if (Phase == (global::CSharpGameEngine.Entities.SystemPhase){Binding.System.Phase} && (!EditorOnly || {Bool(IsEditor)}) && (!RealtimeOnly || {Bool(IsRealtime)})) {{");
            Lines.AddRange(BuildSystemDispatch(Binding,Registry,Contexts,ComponentIndexByType,FieldNameByComponentFqn,ContextNameByFqn));
            Lines.Add("        }");
        }
        Lines.Add("        } finally {");
        Lines.Add("            State.World.EndSystemExecution();");
        Lines.Add("        }");
        Lines.Add("    }");

        // ADR-0070 B1: the Scene Designer's runtime view. It shows the world as the game presents it
        // (every Presentation system) without input, simulation or physics advancing it.
        Lines.Add($"    internal static void RunPresentationFrame(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
        Lines.Add("        if (!State.Enabled) return;");
        Lines.Add("        State.MeasureFrameDelta();");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        if(SpatialWorldEmitter.ShouldEmit(Registry)){ Lines.Add("        State.World.RefreshGlobalSpatialIndex();"); }
        Lines.Add($"        RunPhase(global::CSharpGameEngine.Entities.SystemPhase.Presentation, ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, false, false);");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add("    }");

        bool HasEditorSystems=Systems.Any(static Binding=>Binding.System.ExecuteInEditor);
        bool HasRealtimeEditorSystems=Systems.Any(static Binding=>Binding.System.ExecuteInEditor&&Binding.System.RealtimeInEditor);
        if(HasEditorSystems){
            Lines.Add($"    internal static void RunEditorFrame(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
            Lines.Add("        State.MeasureFrameDelta();");
            Lines.Add($"        RunSimulationTick(ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, true, false);");
            if(SpatialWorldEmitter.ShouldEmit(Registry)){ Lines.Add("        State.World.RefreshGlobalSpatialIndex();"); }
            Lines.Add("    }");
            if(HasRealtimeEditorSystems){
                Lines.Add($"    internal static void RunEditorRealtimeFrame(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
                Lines.Add("        State.MeasureFrameDelta();");
                Lines.Add($"        RunSimulationTick(ref State, ref Systems{BuildContextArgumentSuffix(Contexts)}, true, true);");
                if(SpatialWorldEmitter.ShouldEmit(Registry)){ Lines.Add("        State.World.RefreshGlobalSpatialIndex();"); }
                Lines.Add("    }");
            }
            Lines.Add($"    internal static void ShutdownEditor(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
            Lines.Add("        State.World.BeginSystemExecution();");
            Lines.Add("        try {");
            Lines.AddRange(BuildShutdown(Systems.Where(static Binding=>Binding.System.ExecuteInEditor).Reverse(),Registry,Contexts,ComponentIndexByType,FieldNameByComponentFqn,ContextNameByFqn));
            Lines.Add("        } finally {");
            Lines.Add("            State.World.EndSystemExecution();");
            Lines.Add("        }");
            Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
            Lines.Add("    }");
        }

        Lines.Add($"    internal static void Shutdown(ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems{BuildContextParameterSuffix(Contexts)}) {{");
        Lines.Add("        State.World.BeginSystemExecution();");
        Lines.Add("        try {");
        Lines.AddRange(BuildShutdown(Systems.AsEnumerable().Reverse(),Registry,Contexts,ComponentIndexByType,FieldNameByComponentFqn,ContextNameByFqn));
        Lines.Add("        } finally {");
        Lines.Add("            State.World.EndSystemExecution();");
        Lines.Add("        }");
        Lines.Add("        State.World.PlaybackStructuralChanges(ref State);");
        Lines.Add("    }");
        Lines.Add($"    internal static void Run({BuildRunParameterList(Contexts)}) {{");
        Lines.Add("        GeneratedSystemSet Systems = default;");
        Lines.Add(HasEngineHost
            ?"        var Scheduler = EngineHost.FixedTicks;"
            :"        var Scheduler = new global::CSharpGameEngine.Runtime.Simulation.FixedTickScheduler();");
        Lines.Add("        var PreviousCounter = global::System.Diagnostics.Stopwatch.GetTimestamp();");
        Lines.Add("        try {");
        Lines.Add("            while (State.Enabled) {");
        Lines.Add("                var CurrentCounter = global::System.Diagnostics.Stopwatch.GetTimestamp();");
        Lines.Add("                var ElapsedCounter = CurrentCounter - PreviousCounter;");
        Lines.Add("                PreviousCounter = CurrentCounter;");
        Lines.Add($"                RunFrame(ref State, ref Systems, ref Scheduler, ElapsedCounter, global::System.Diagnostics.Stopwatch.Frequency{BuildContextArgumentSuffix(Contexts)});");
        Lines.Add("            }");
        Lines.Add("        } finally {");
        Lines.Add($"            Shutdown(ref State, ref Systems{BuildContextArgumentSuffix(Contexts)});");
        Lines.Add("        }");
        Lines.Add("    }");
        Lines.Add("}");
        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }

    private static IEnumerable<string> BuildSystemDispatch(
        SystemBinding Binding,GameSystemRegistry Registry,List<ContextBinding> Contexts,
        Dictionary<string,int> ComponentIndexByType,Dictionary<string,string> FieldNameByComponentFqn,
        Dictionary<string,string> ContextNameByFqn){
        List<string> Lines=[];
        var WideMask=Registry.ComponentsByIndex.Length>64;
        foreach(GameSystemMethodModel Method in Binding.System.Methods){
            if(Method.Role!=GameSystemMethodRole.Dispatch){ continue; }
            if(Binding.System.IsWorldSystem&&Method.Components.Length==0){
                Lines.Add("            if (!State.Enabled) return;");
                Lines.Add(Method.ReturnsBool
                    ?$"            if (!Systems.{Binding.VariableName}.Update({BuildCallArguments(Method,null,ContextNameByFqn,FieldNameByComponentFqn)})) return;"
                    :$"            Systems.{Binding.VariableName}.Update({BuildCallArguments(Method,null,ContextNameByFqn,FieldNameByComponentFqn)});");
                continue;
            }
            MethodComponentMask MethodMask=BuildMethodMask(Method,ComponentIndexByType);
            foreach(GameSystemArchetypeInfo Archetype in Registry.Archetypes){
                if(!Contains(Archetype,MethodMask,WideMask)){ continue; }
                Lines.Add($"            for (var Index = State.World.{Archetype.Name}.Count - 1; Index >= 0; Index--) {{");
                Lines.Add("                if (!State.Enabled) return;");
                Lines.Add($"                if (!State.World.{Archetype.Name}.IsEntityEnabledUnchecked(Index) || !State.World.{Archetype.Name}.AreComponentsEnabledUnchecked(Index, 0x{MethodMask.Low:X16}UL{(WideMask?$", 0x{MethodMask.High:X16}UL":string.Empty)})) continue;");
                if(Method.Components.Any(static Component=>!Component.IsReadOnly)){
                    Lines.Add("                var Version = State.World.AdvanceChangeVersion();");
                }
                foreach(GameSystemComponentParameterModel Component in Method.Components.Where(static Component=>!Component.IsReadOnly)){
                    Lines.Add($"                State.World.{Archetype.Name}.Mark{FieldNameByComponentFqn[Component.TypeFullyQualifiedName]}ChangedUnchecked(Index, Version);");
                }
                // ADR-0072: an entity system's result has no effect (this is the loop's last statement), so a bool is discarded.
                Lines.Add(Method.ReturnsBool
                    ?$"                _ = Systems.{Binding.VariableName}.Update({BuildCallArguments(Method,Archetype,ContextNameByFqn,FieldNameByComponentFqn)});"
                    :$"                Systems.{Binding.VariableName}.Update({BuildCallArguments(Method,Archetype,ContextNameByFqn,FieldNameByComponentFqn)});");
                Lines.Add("            }");
            }
        }
        return Lines;
    }

    private static IEnumerable<string> BuildShutdown(
        IEnumerable<SystemBinding> Systems,GameSystemRegistry Registry,List<ContextBinding> Contexts,
        Dictionary<string,int> ComponentIndexByType,Dictionary<string,string> FieldNameByComponentFqn,
        Dictionary<string,string> ContextNameByFqn){
        List<string> Lines=[];
        var WideMask=Registry.ComponentsByIndex.Length>64;
        foreach(SystemBinding Binding in Systems){
            foreach(GameSystemMethodModel Method in Binding.System.Methods.Reverse()){
                if(Method.Role!=GameSystemMethodRole.Shutdown){ continue; }
                if(Binding.System.IsWorldSystem&&Method.Components.Length==0){
                    Lines.Add($"        Systems.{Binding.VariableName}.Shutdown({BuildCallArguments(Method,null,ContextNameByFqn,FieldNameByComponentFqn)});");
                    continue;
                }
                MethodComponentMask MethodMask=BuildMethodMask(Method,ComponentIndexByType);
                for(int ArchetypeIndex=Registry.Archetypes.Length-1;ArchetypeIndex>=0;ArchetypeIndex--){
                    GameSystemArchetypeInfo Archetype=Registry.Archetypes[ArchetypeIndex];
                    if(!Contains(Archetype,MethodMask,WideMask)){ continue; }
                    Lines.Add($"        for (var Index = State.World.{Archetype.Name}.Count - 1; Index >= 0; Index--) {{");
                    Lines.Add($"            if (!State.World.{Archetype.Name}.IsEntityEnabledUnchecked(Index) || !State.World.{Archetype.Name}.AreComponentsEnabledUnchecked(Index, 0x{MethodMask.Low:X16}UL{(WideMask?$", 0x{MethodMask.High:X16}UL":string.Empty)})) continue;");
                    if(Method.Components.Any(static Component=>!Component.IsReadOnly)){
                        Lines.Add("            var Version = State.World.AdvanceChangeVersion();");
                    }
                    foreach(GameSystemComponentParameterModel Component in Method.Components.Where(static Component=>!Component.IsReadOnly)){
                        Lines.Add($"            State.World.{Archetype.Name}.Mark{FieldNameByComponentFqn[Component.TypeFullyQualifiedName]}ChangedUnchecked(Index, Version);");
                    }
                    Lines.Add($"            Systems.{Binding.VariableName}.Shutdown({BuildCallArguments(Method,Archetype,ContextNameByFqn,FieldNameByComponentFqn)});");
                    Lines.Add("        }");
                }
            }
        }
        return Lines;
    }

    private static string BuildCallArguments(GameSystemMethodModel Method,GameSystemArchetypeInfo? Archetype,
        Dictionary<string,string> ContextNameByFqn,Dictionary<string,string> FieldNameByComponentFqn){
        List<string> Arguments=[];
        foreach(GameSystemParameterSlot Slot in Method.CallOrder){
            switch(Slot.Role){
                case GameSystemParameterRole.Entity:
                    Arguments.Add($"State.World.{Archetype!.Value.Name}.GetEntityRefUnchecked(Index)");
                    break;
                case GameSystemParameterRole.Component:
                    GameSystemComponentParameterModel Component=Method.Components[Slot.Index];
                    Arguments.Add($"{(Component.IsReadOnly?"in ":"ref ")}State.World.{Archetype!.Value.Name}.Get{FieldNameByComponentFqn[Component.TypeFullyQualifiedName]}RefUnchecked(Index)");
                    break;
                case GameSystemParameterRole.Context:
                    GameSystemContextParameterModel Context=Method.Contexts[Slot.Index];
                    Arguments.Add($"{(Context.IsReferenceType?string.Empty:"in ")}{ContextNameByFqn[Context.TypeFullyQualifiedName]}");
                    break;
                case GameSystemParameterRole.State:
                    Arguments.Add("ref State");
                    break;
            }
        }
        return string.Join(", ",Arguments);
    }

    private static MethodComponentMask BuildMethodMask(GameSystemMethodModel Method,Dictionary<string,int> ComponentIndexByType){
        ulong Low=0;
        ulong High=0;
        foreach(GameSystemComponentParameterModel Component in Method.Components){
            var Index=ComponentIndexByType[Component.TypeFullyQualifiedName];
            if(Index<64){ Low|=1UL<<Index; }
            else { High|=1UL<<(Index-64); }
        }
        return new MethodComponentMask(Low,High);
    }

    private static bool Contains(GameSystemArchetypeInfo Archetype,MethodComponentMask Method,bool WideMask){
        if((Archetype.MaskLow&Method.Low)!=Method.Low){ return false; }
        return !WideMask||(Archetype.MaskHigh&Method.High)==Method.High;
    }

    private readonly struct MethodComponentMask(ulong Low,ulong High){
        internal readonly ulong Low=Low;
        internal readonly ulong High=High;
    }

    private readonly struct SystemBinding(string TypeReference,string VariableName,GameSystemResult System){
        internal readonly string TypeReference=TypeReference;
        internal readonly string VariableName=VariableName;
        internal readonly GameSystemResult System=System;
    }

    private readonly struct ContextBinding(string TypeFullyQualifiedName,string ParameterName,bool IsReferenceType){
        internal readonly string TypeFullyQualifiedName=TypeFullyQualifiedName;
        internal readonly string ParameterName=ParameterName;
        internal readonly bool IsReferenceType=IsReferenceType;
    }

    private static List<SystemBinding> BuildSystemBindings(List<GameSystemResult> SourceSystems){
        List<SystemBinding> Systems=[];
        HashSet<string> UsedNames=new(StringComparer.Ordinal);
        foreach(GameSystemResult System in SourceSystems){ Systems.Add(new SystemBinding(System.GlobalQualifiedName,BuildLocalName(System.ClassName,UsedNames),System)); }
        return Systems;
    }

    private static List<ContextBinding> BuildContextBindings(List<GameSystemResult> SourceSystems){
        Dictionary<string,bool> ReferenceKinds=new(StringComparer.Ordinal);
        foreach(GameSystemResult System in SourceSystems){
            foreach(GameSystemMethodModel Method in System.Methods){
                if(Method.Role is not (GameSystemMethodRole.Dispatch or GameSystemMethodRole.Shutdown)){ continue; }
                foreach(GameSystemContextParameterModel Parameter in Method.Contexts){ ReferenceKinds[Parameter.TypeFullyQualifiedName]=Parameter.IsReferenceType; }
            }
        }
        HashSet<string> UsedNames=new(StringComparer.Ordinal);
        List<ContextBinding> Result=[];
        foreach(string Fqn in ReferenceKinds.Keys.OrderBy(static Value=>Value,StringComparer.Ordinal)){
            Result.Add(new ContextBinding(Fqn,BuildLocalName(GameSystemIndexAssigner.ExtractSimpleTypeName(Fqn),UsedNames),ReferenceKinds[Fqn]));
        }
        return Result;
    }

    internal static string BuildLocalName(string SimpleTypeName,HashSet<string> UsedNames){
        string Candidate=char.ToUpperInvariant(SimpleTypeName[0])+SimpleTypeName.Substring(1);
        if(SyntaxFacts.GetKeywordKind(Candidate)!=SyntaxKind.None||SyntaxFacts.GetContextualKeywordKind(Candidate)!=SyntaxKind.None){ Candidate="@"+Candidate; }
        if(UsedNames.Add(Candidate)){ return Candidate; }
        int Suffix=2;
        while(!UsedNames.Add(Candidate+Suffix)){ Suffix++; }
        return Candidate+Suffix;
    }

    private static string BuildSystemSetFrameParameterList(List<ContextBinding> Contexts)=>
        "ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems, ref global::CSharpGameEngine.Runtime.Simulation.FixedTickScheduler Scheduler, long ElapsedCounter, long CounterFrequency"+BuildContextParameterSuffix(Contexts);
    private static string BuildPhaseParameterList(List<ContextBinding> Contexts)=>
        "ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems"+BuildContextParameterSuffix(Contexts)+", bool EditorOnly, bool RealtimeOnly";
    private static string BuildSimulationTickParameterList(List<ContextBinding> Contexts)=>
        "ref global::CSharpGameEngine.Entities.State State, ref GeneratedSystemSet Systems"+BuildContextParameterSuffix(Contexts)+", bool EditorOnly, bool RealtimeOnly";
    private static string BuildLegacyFrameParameterList(List<SystemBinding> Systems,List<ContextBinding> Contexts){
        List<string> Parameters=["ref global::CSharpGameEngine.Entities.State State"];
        Parameters.AddRange(Systems.Select(static System=>$"ref {System.TypeReference} {System.VariableName}"));
        Parameters.Add("ref global::CSharpGameEngine.Runtime.Simulation.FixedTickScheduler Scheduler");
        Parameters.Add("long ElapsedCounter");
        Parameters.Add("long CounterFrequency");
        Parameters.AddRange(Contexts.Select(static Context=>$"{(Context.IsReferenceType?string.Empty:"in ")}{Context.TypeFullyQualifiedName} {Context.ParameterName}"));
        return string.Join(", ",Parameters);
    }
    private static string BuildRunParameterList(List<ContextBinding> Contexts){
        List<string> Parameters=["ref global::CSharpGameEngine.Entities.State State"];
        Parameters.AddRange(Contexts.Select(static Context=>$"{(Context.IsReferenceType?string.Empty:"in ")}{Context.TypeFullyQualifiedName} {Context.ParameterName}"));
        return string.Join(", ",Parameters);
    }
    private static string BuildContextParameterSuffix(List<ContextBinding> Contexts)=>Contexts.Count==0?string.Empty:", "+string.Join(", ",Contexts.Select(static Context=>$"{(Context.IsReferenceType?string.Empty:"in ")}{Context.TypeFullyQualifiedName} {Context.ParameterName}"));
    private static string BuildContextArgumentSuffix(List<ContextBinding> Contexts)=>Contexts.Count==0?string.Empty:", "+string.Join(", ",Contexts.Select(static Context=>$"{(Context.IsReferenceType?string.Empty:"in ")}{Context.ParameterName}"));
    private static string Bool(bool Value)=>Value?"true":"false";
}
