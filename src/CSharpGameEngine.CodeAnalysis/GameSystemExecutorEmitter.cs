using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// 1つの<c>[Update]</c>メソッドごとに、Query定義とSoA行ループを持つ<c>internal static class
/// {Method}_Executor</c>を生成する。ユーザーのクラスには何も追加しない(名前空間スコープの
/// 独立した型として出力するため、ユーザーのメンバー名との衝突が原理的に起きず、<c>[GameSystem]</c>
/// クラスに<c>partial</c>を強制する必要もない)。診断が1件でもあるクラスはこのクラス分の
/// Executor生成を全てスキップする(壊れた部分実装による二次的なコンパイルエラーを避けるため、
/// 既存2ジェネレータと同じ診断ゲートパターン)。
/// </summary>
internal static class GameSystemExecutorEmitter
{
    internal static void Emit(SourceProductionContext context, GameSystemClassResult result)
    {
        foreach (Diagnostic diagnostic in result.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic);
        }

        if (result.Diagnostics.Length > 0)
        {
            return;
        }

        foreach (SystemMethodModel method in result.Methods)
        {
            string hintName = result.Namespace is null
                ? $"{result.ClassName}.{method.MethodName}.Executor.g.cs"
                : $"{result.Namespace}.{result.ClassName}.{method.MethodName}.Executor.g.cs";

            string source = string.Join("\n", BuildSourceLines(result, method));
            context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
        }
    }

    private static List<string> BuildSourceLines(GameSystemClassResult result, SystemMethodModel method)
    {
        List<int> accessIndexByComponentIndex = BuildAccessIndexLookup(method, out int accessCount);

        List<string> lines = ["// <auto-generated/>", "#nullable enable"];

        if (result.Namespace is not null)
        {
            lines.Add("");
            lines.Add($"namespace {result.Namespace};");
        }

        lines.Add("");
        lines.Add($"internal static class {method.BuildExecutorTypeName(result.ClassName)}");
        lines.Add("{");
        lines.Add("    private static readonly global::CSharpGameEngine.Entities.EntityQuery Query = global::CSharpGameEngine.Entities.EntityQuery.Create(");
        lines.Add("        all: new int[]");
        lines.Add("        {");

        foreach (ComponentParameterModel component in method.ComponentParameters)
        {
            lines.Add($"            global::CSharpGameEngine.Entities.ComponentType<{component.TypeFullyQualifiedName}>.Id,");
        }

        lines.Add("        },");

        if (method.WithoutComponentTypes.Length == 0)
        {
            lines.Add("        none: global::System.Array.Empty<int>(),");
        }
        else
        {
            lines.Add("        none: new int[]");
            lines.Add("        {");

            foreach (string withoutType in method.WithoutComponentTypes)
            {
                lines.Add($"            global::CSharpGameEngine.Entities.ComponentType<{withoutType}>.Id,");
            }

            lines.Add("        },");
        }

        if (accessCount == 0)
        {
            lines.Add("        access: global::System.Array.Empty<int>());");
        }
        else
        {
            lines.Add("        access: new int[]");
            lines.Add("        {");

            foreach (ComponentParameterModel component in method.ComponentParameters)
            {
                if (!component.IsTag)
                {
                    lines.Add($"            global::CSharpGameEngine.Entities.ComponentType<{component.TypeFullyQualifiedName}>.Id,");
                }
            }

            lines.Add("        });");
        }

        lines.Add("");
        lines.Add($"    internal static void Execute({BuildExecuteParameterList(method)})");
        lines.Add("    {");
        lines.Add("        global::CSharpGameEngine.Entities.QueryMatches matches = Query.Update(world);");

        foreach (ComponentParameterModel component in method.ComponentParameters)
        {
            if (component.IsTag)
            {
                lines.Add($"        {component.TypeFullyQualifiedName} {component.ParameterName} = default;");
            }
        }

        if (method.UsesCommands)
        {
            lines.Add("        global::CSharpGameEngine.Entities.EntityCommandBuffer commands = world.Commands;");
        }

        lines.Add("        for (int matchIndex = 0; matchIndex < matches.Count; matchIndex++)");
        lines.Add("        {");
        lines.Add("            global::CSharpGameEngine.Entities.Archetype archetype = matches.ArchetypeAt(matchIndex);");
        lines.Add("            int count = archetype.Count;");
        lines.Add("            if (count == 0)");
        lines.Add("            {");
        lines.Add("                continue;");
        lines.Add("            }");

        for (int i = 0; i < method.ComponentParameters.Length; i++)
        {
            ComponentParameterModel component = method.ComponentParameters[i];

            if (component.IsTag)
            {
                continue;
            }

            int accessIndex = accessIndexByComponentIndex[i];
            string spanType = component.Access == ComponentAccess.Write ? "global::System.Span" : "global::System.ReadOnlySpan";
            string spanMethod = component.Access == ComponentAccess.Write ? "GetSpan" : "GetReadOnlySpan";
            lines.Add($"            {spanType}<{component.TypeFullyQualifiedName}> {component.ParameterName} = archetype.{spanMethod}<{component.TypeFullyQualifiedName}>(matches.ColumnAt(matchIndex, {accessIndex}));");
        }

        if (method.UsesCurrentEntity)
        {
            lines.Add("            global::System.ReadOnlySpan<global::CSharpGameEngine.Entities.Entity> entities = archetype.Entities;");
        }

        lines.Add("            for (int row = 0; row < count; row++)");
        lines.Add("            {");
        lines.Add($"                global::{result.ClassFullyQualifiedName}.{method.MethodName}(");

        List<string> callArguments = BuildCallArguments(method);

        for (int i = 0; i < callArguments.Count; i++)
        {
            string suffix = i == callArguments.Count - 1 ? ");" : ",";
            lines.Add($"                    {callArguments[i]}{suffix}");
        }

        lines.Add("            }");
        lines.Add("        }");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");

        return lines;
    }

    /// <summary>
    /// <see cref="SystemMethodModel.ComponentParameters"/>の各要素(タグを含む)に対して、
    /// 非タグ成分だけを数えたQueryの<c>access</c>配列上のインデックスを対応付ける
    /// (タグ自身にはインデックスは存在しない、値は使われない)。
    /// </summary>
    private static List<int> BuildAccessIndexLookup(SystemMethodModel method, out int accessCount)
    {
        List<int> lookup = new(method.ComponentParameters.Length);
        int next = 0;

        foreach (ComponentParameterModel component in method.ComponentParameters)
        {
            if (component.IsTag)
            {
                lookup.Add(-1);
            }
            else
            {
                lookup.Add(next);
                next++;
            }
        }

        accessCount = next;
        return lookup;
    }

    private static string BuildExecuteParameterList(SystemMethodModel method)
    {
        List<string> parameters = ["global::CSharpGameEngine.Entities.World world"];

        foreach (ContextParameterModel context in method.ContextParameters)
        {
            string modifier = context.IsReferenceType ? string.Empty : "in ";
            parameters.Add($"{modifier}{context.TypeFullyQualifiedName} {context.ParameterName}");
        }

        return string.Join(", ", parameters);
    }

    private static List<string> BuildCallArguments(SystemMethodModel method)
    {
        List<string> arguments = [];

        foreach (ParameterSlot slot in method.CallOrder)
        {
            switch (slot.Role)
            {
                case ParameterRole.Component:
                    ComponentParameterModel component = method.ComponentParameters[slot.Index];
                    string accessor = component.IsTag ? component.ParameterName : $"{component.ParameterName}[row]";
                    string modifier = component.Access == ComponentAccess.Write ? "ref " : "in ";
                    arguments.Add($"{modifier}{accessor}");
                    break;
                case ParameterRole.Context:
                    ContextParameterModel context = method.ContextParameters[slot.Index];
                    string contextModifier = context.IsReferenceType ? string.Empty : "in ";
                    arguments.Add($"{contextModifier}{context.ParameterName}");
                    break;
                case ParameterRole.CurrentEntity:
                    arguments.Add("entities[row]");
                    break;
                case ParameterRole.Commands:
                    arguments.Add("commands");
                    break;
            }
        }

        return arguments;
    }
}
