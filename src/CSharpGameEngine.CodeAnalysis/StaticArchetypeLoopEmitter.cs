using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>internal static class GeneratedGameLoop</c>に<c>RunFrame</c>(1フレーム分、全Archetypeを
/// 後方swap-back安全な順序で走査し、部分集合一致する全Systemの全<c>Update</c>オーバーロードを呼ぶ)と
/// <c>Run</c>(System実体を生成し<c>while(State.Enabled)</c>で<c>RunFrame</c>を回す)を生成する。
/// トップレベルステートメントとしては出力しない(1コンパイルにつきトップレベルステートメントを含む
/// ファイルは1つまでという制約 - CS8802 - のため、SGが安全に保証できない。ADR-0032決定事項6)。
/// サンプルの手書き<c>.g.cs</c>はメインループで<c>System0</c>しか呼んでいないが、これは書き漏れと
/// ユーザーに確認済みのため、<c>ISystem</c>を実装する全structを対象に含める(ADR-0032決定事項5)。
/// </summary>
internal static class StaticArchetypeLoopEmitter
{
    private const string HintName = "StaticArchetype.Loop.g.cs";

    internal static void Emit(SourceProductionContext context, StaticArchetypeRegistry registry)
    {
        if (registry.Archetypes.Length == 0 || registry.ValidSystems.Length == 0)
        {
            return;
        }

        Dictionary<string, int> componentIndexByType = new(StringComparer.Ordinal);

        foreach (StaticArchetypeComponentInfo component in registry.ComponentsByIndex)
        {
            componentIndexByType[component.TypeFullyQualifiedName] = component.Index;
        }

        List<(string TypeReference, string VariableName, StaticArchetypeSystemResult System)> systems =
            [.. registry.ValidSystems.Select(s => (BuildSystemTypeReference(s), s.ClassName, s))];

        List<string> lines = ["// <auto-generated/>", "#nullable enable", "", "internal static class GeneratedGameLoop", "{"];

        lines.Add($"    internal static void RunFrame({BuildRunFrameParameterList(systems)}){{");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.AddRange(BuildArchetypeLoopBody(archetype, systems, componentIndexByType));
        }

        lines.Add("");
        lines.Add("        State.World.PlaybackMoveArchetypes(ref State);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    internal static void Run(ref State State){");

        foreach ((string typeReference, string variableName, _) in systems)
        {
            lines.Add($"        var {variableName} = new {typeReference}();");
        }

        lines.Add("        while(State.Enabled){");
        lines.Add($"            RunFrame(ref State, {string.Join(", ", systems.Select(s => $"ref {s.VariableName}"))});");
        lines.Add("        }");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");

        string source = string.Join("\n", lines);
        context.AddSource(HintName, SourceText.From(source, Encoding.UTF8));
    }

    private static string BuildSystemTypeReference(StaticArchetypeSystemResult system) =>
        system.Namespace is null ? system.ClassName : $"global::{system.Namespace}.{system.ClassName}";

    private static string BuildRunFrameParameterList(List<(string TypeReference, string VariableName, StaticArchetypeSystemResult System)> systems)
    {
        List<string> parameters = ["ref State State"];
        parameters.AddRange(systems.Select(s => $"ref {s.TypeReference} {s.VariableName}"));
        return string.Join(", ", parameters);
    }

    private static List<string> BuildArchetypeLoopBody(
        StaticArchetypeArchetypeInfo archetype,
        List<(string TypeReference, string VariableName, StaticArchetypeSystemResult System)> systems,
        Dictionary<string, int> componentIndexByType)
    {
        List<string> lines =
        [
            $"        for(var Index=State.World.{archetype.ListFieldName}.Count-1;Index>=0;Index--){{",
            $"            ref var Archetype=ref State.World.{archetype.ListFieldName}[Index];",
        ];

        foreach ((string _, string variableName, StaticArchetypeSystemResult system) in systems)
        {
            foreach (StaticArchetypeUpdateOverloadModel overload in system.Overloads)
            {
                long overloadMask = 0;

                foreach (StaticArchetypeComponentParameterModel component in overload.Components)
                {
                    overloadMask |= 1L << componentIndexByType[component.TypeFullyQualifiedName];
                }

                if ((archetype.Mask & overloadMask) != overloadMask)
                {
                    continue;
                }

                List<string> callArguments = [];

                if (overload.HasLeadingEntityParameter)
                {
                    callArguments.Add("Archetype.Entity");
                }

                foreach (StaticArchetypeComponentParameterModel component in overload.Components)
                {
                    string fieldName = StaticArchetypeTypesEmitter.ExtractSimpleTypeName(component.TypeFullyQualifiedName);
                    callArguments.Add($"ref Archetype.{fieldName}");
                }

                callArguments.Add("ref State");

                lines.Add($"            if(!{variableName}.Update({string.Join(",", callArguments)})) continue;");
            }
        }

        lines.Add("        }");

        return lines;
    }
}
