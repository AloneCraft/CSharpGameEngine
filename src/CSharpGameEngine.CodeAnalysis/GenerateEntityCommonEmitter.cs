using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <see cref="GenerateEntityAnalysisResult"/>から、AoS/SoA両バックエンドで共通の生成物
/// (<c>{Type}CreateInfo</c>、<c>{Type}GeneratedMetadata</c>、<c>{Type}</c>のFacade partial実装)を
/// 生成する。このファイルは<c>{Type}Store</c>の公開/internal API(<c>Create</c>/<c>IsAlive</c>/
/// <c>Destroy</c>/<c>Get{Name}Ref</c>)だけを参照するため、AoS/SoAどちらのバックエンドでも
/// 一字一句同じソースが生成される。
/// </summary>
internal static class GenerateEntityCommonEmitter
{
    internal static void Emit(SourceProductionContext context, GenerateEntityAnalysisResult result)
    {
        string hintName = GenerateEntityEmitterSupport.BuildHintName(result, "Common");
        string source = string.Join("\n", BuildSourceLines(result));
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    private static List<string> BuildSourceLines(GenerateEntityAnalysisResult result)
    {
        List<string> lines = ["// <auto-generated/>", "#nullable enable"];

        GenerateEntityEmitterSupport.OpenContainingScope(lines, result);

        AppendCreateInfo(lines, result);
        AppendGeneratedMetadata(lines, result);
        AppendFacade(lines, result);

        GenerateEntityEmitterSupport.CloseContainingScope(lines, result);
        lines.Add("");

        return lines;
    }

    private static void AppendCreateInfo(List<string> lines, GenerateEntityAnalysisResult result)
    {
        lines.Add("");
        lines.Add($"public struct {result.StructName}CreateInfo");
        lines.Add("{");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add($"    public {component.ComponentTypeFullyQualifiedName} {component.PropertyName};");
        }

        lines.Add("}");
    }

    private static void AppendGeneratedMetadata(List<string> lines, GenerateEntityAnalysisResult result)
    {
        lines.Add("");
        lines.Add($"internal static class {result.StructName}GeneratedMetadata");
        lines.Add("{");
        lines.Add("    private static readonly string[] normalizedSignatureBacking =");
        lines.Add("    {");

        foreach (GenerateEntityComponentModel component in result.NormalizedComponents)
        {
            lines.Add($"        \"{component.ComponentTypeFullyQualifiedName}\",");
        }

        lines.Add("    };");
        lines.Add("");
        lines.Add("    internal static global::System.ReadOnlySpan<string> NormalizedSignature => normalizedSignatureBacking;");
        lines.Add("}");
    }

    private static void AppendFacade(List<string> lines, GenerateEntityAnalysisResult result)
    {
        string structName = result.StructName;

        lines.Add("");
        lines.Add($"public partial struct {structName} : global::System.IEquatable<{structName}>");
        lines.Add("{");
        lines.Add($"    private readonly {structName}Store? _store;");
        lines.Add("    private readonly global::CSharpGameEngine.Ecs.Entity _entity;");
        lines.Add("");
        lines.Add($"    internal {structName}({structName}Store store, global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        this._store = store;");
        lines.Add("        this._entity = entity;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public global::CSharpGameEngine.Ecs.Entity Entity => this._entity;");
        lines.Add("");
        lines.Add("    public bool IsAlive => this._store is not null && this._store.IsAlive(this._entity);");

        foreach (GenerateEntityComponentModel component in result.DeclarationOrderedComponents)
        {
            lines.Add("");
            lines.Add($"    public partial {component.ComponentTypeFullyQualifiedName} {component.PropertyName}");
            lines.Add("    {");
            lines.Add($"        get {{ return this._store!.Get{component.PropertyName}Ref(this._entity); }}");
            lines.Add($"        set {{ this._store!.Get{component.PropertyName}Ref(this._entity) = value; }}");
            lines.Add("    }");
            lines.Add("");
            lines.Add($"    public ref {component.ComponentTypeFullyQualifiedName} {component.PropertyName}Ref");
            lines.Add("    {");
            lines.Add($"        get {{ return ref this._store!.Get{component.PropertyName}Ref(this._entity); }}");
            lines.Add("    }");
        }

        lines.Add("");
        lines.Add("    public void Destroy()");
        lines.Add("    {");
        lines.Add("        this._store!.Destroy(this._entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public bool Equals({structName} other)");
        lines.Add("    {");
        lines.Add("        return object.ReferenceEquals(this._store, other._store)");
        lines.Add("            && this._entity == other._entity;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public override bool Equals(object? obj)");
        lines.Add("    {");
        lines.Add($"        return obj is {structName} other && this.Equals(other);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public override int GetHashCode()");
        lines.Add("    {");
        lines.Add("        return global::System.HashCode.Combine(this._store, this._entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public static bool operator ==({structName} left, {structName} right)");
        lines.Add("    {");
        lines.Add("        return left.Equals(right);");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public static bool operator !=({structName} left, {structName} right)");
        lines.Add("    {");
        lines.Add("        return !left.Equals(right);");
        lines.Add("    }");
        lines.Add("}");
    }
}
