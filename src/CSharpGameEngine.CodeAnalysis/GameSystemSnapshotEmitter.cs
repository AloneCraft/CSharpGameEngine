using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// 生きた<c>World</c>の内容を、実行時の型知識なしで読み取れる形へ落とす<c>WorldSnapshot.Capture</c>を
/// 生成する(ADR-0033決定事項6)。
///
/// <para>
/// 閉集合Archetype方式では<c>CSharpGameEngine.Entities</c>が共有バイナリでなくなる
/// (<c>partial struct World</c>はコンパイル単位でしか合成できないため、各消費プロジェクトが
/// ソースを取り込んで独自にコンパイルする)。よってVSIXプレビューブリッジ
/// (<c>CSharpGameEngine.SceneAuthoring.Cli</c>)は対象プロセスの<c>World</c>を自分の型として扱えず、
/// 旧実装が使っていた<c>ArchetypeCount</c>/<c>GetArchetype(i)</c>/<c>ComponentTypeIds</c>のような
/// 「実行時に全Archetypeを汎用列挙する」内部APIも閉集合方式には存在しない。
/// </para>
///
/// <para>
/// そこで、Generatorがコンパイル時に持っている「全<c>ArchetypeNN</c>のフィールド一覧」という知識を
/// 使って、ボックス化した<c>object[]</c>の配列を返すメソッドを機械的に生成する。CLIはこれを
/// リフレクションで1回呼ぶだけで済み、<c>InternalsVisibleTo</c>も不要になる。デリゲートをALC境界
/// 越しに渡す必要が無いよう、コールバックではなく戻り値ベースにしてある。
/// </para>
///
/// <para>
/// <c>public</c>にするのは、CLIのリフレクションが<c>BindingFlags.Public</c>だけで到達できるように
/// するための意図的な例外(このランタイムの他の型は<c>internal</c>基調)。
/// </para>
/// </summary>
internal static class GameSystemSnapshotEmitter
{
    private const string HintName = "GameSystem.Snapshot.g.cs";
    private const string ParentComponentFullyQualifiedName = "global::CSharpGameEngine.Entities.Parent";

    internal static void Emit(SourceProductionContext context, GameSystemRegistry registry)
    {
        List<string> lines =
        [
            "// <auto-generated/>",
            "#nullable enable",
            "",
            "namespace CSharpGameEngine.Entities;",
            "",
            "/// <summary>1 Entity分のスナップショット。CLIはこの型をリフレクションで読む。</summary>",
            "public struct ArchetypeSnapshotEntry",
            "{",
            "    public int EntityId;",
            "    public int ParentEntityId;",
            "    public bool HasParent;",
            "    public string ArchetypeName;",
            "    public object[] ComponentValues;",
            "}",
            "",
            "public static class WorldSnapshot",
            "{",
            "    public static ArchetypeSnapshotEntry[] Capture(in World World)",
            "    {",
            "        var Entries = new global::System.Collections.Generic.List<ArchetypeSnapshotEntry>();",
        ];

        foreach (GameSystemArchetypeInfo archetype in registry.Archetypes)
        {
            List<(string TypeFullyQualifiedName, string FieldName)> components = GameSystemTypesEmitter.BuildComponentFields(archetype, registry);
            string? parentFieldName = components.FirstOrDefault(c => c.TypeFullyQualifiedName == ParentComponentFullyQualifiedName).FieldName;

            lines.Add("");
            lines.Add($"        for (var Index = 0; Index < World.{archetype.Name}.Count; Index++)");
            lines.Add("        {");
            lines.Add("            Entries.Add(new ArchetypeSnapshotEntry");
            lines.Add("            {");
            lines.Add($"                EntityId = World.{archetype.Name}.GetEntityRefUnchecked(Index).Id,");

            if (parentFieldName is not null)
            {
                lines.Add($"                ParentEntityId = World.{archetype.Name}.Get{parentFieldName}RefUnchecked(Index).Value.Id,");
                lines.Add("                HasParent = true,");
            }
            else
            {
                lines.Add("                ParentEntityId = -1,");
                lines.Add("                HasParent = false,");
            }

            lines.Add($"                ArchetypeName = \"{archetype.Name}\",");
            lines.Add($"                ComponentValues = new object[] {{ {string.Join(", ", components.Select(c => $"World.{archetype.Name}.Get{c.FieldName}RefUnchecked(Index)"))} }},");
            lines.Add("            });");
            lines.Add("        }");
        }

        lines.Add("");
        lines.Add("        return Entries.ToArray();");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");

        context.AddSource(HintName, SourceText.From(string.Join("\n", lines), Encoding.UTF8));
    }
}


