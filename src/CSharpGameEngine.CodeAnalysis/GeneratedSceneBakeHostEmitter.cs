using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>決定論的な headless simulation Bake 用の、コンパイル時シーン dispatcher を生成します。</summary>
internal static class GeneratedSceneBakeHostEmitter {
    private const string EngineHostType="global::CSharpGameEngine.Runtime.Windows.EngineHost";
    private const string HintName="GameSystem.SceneBakeHost.g.cs";

    internal static void Emit(
        SourceProductionContext Context,IReadOnlyList<SceneEmitModel> Scenes,
        GameSystemRegistry Registry,GenerationGate Gate){
        if(!Gate.HasSceneBakeContract||Scenes.Count==0||Registry.Archetypes.Length==0
            ||!GameSystemLoopEmitter.HasDispatchSystem(Registry.ValidSystems)){
            return;
        }
        string[]ContextTypes=Registry.ValidSystems
            .SelectMany(static System=>System.Methods)
            .Where(static Method=>Method.Role is GameSystemMethodRole.Dispatch or GameSystemMethodRole.Shutdown)
            .SelectMany(static Method=>Method.Contexts)
            .Select(static Parameter=>Parameter.TypeFullyQualifiedName)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static Value=>Value,StringComparer.Ordinal)
            .ToArray();
        if(ContextTypes.Length!=1||ContextTypes[0]!=EngineHostType){ return; }

        List<string>Lines=[
            "// <auto-generated/>",
            "#nullable enable",
            "namespace CSharpGameEngine.Generated;",
            "public static class GeneratedSceneBakeHost {",
            "    public static bool TryBake(",
            "        string? SceneName, int TickCount, string? DependencyHash, global::System.IO.Stream? Output,",
            "        global::System.Threading.CancellationToken CancellationToken, out string Error) {",
            "        Error = string.Empty;",
            "        if (string.IsNullOrWhiteSpace(SceneName)) { Error = "+Quote("A fully-qualified scene name is required.")+"; return false; }",
            "        if (TickCount is < 1 or > global::CSharpGameEngine.Runtime.Physics.PhysicsCacheSerializer.MaximumFrameCount) {",
            "            Error = "+Quote("Tick count is outside the supported physics cache range.")+"; return false;",
            "        }",
            "        if (string.IsNullOrWhiteSpace(DependencyHash)) { Error = "+Quote("A dependency hash is required.")+"; return false; }",
            "        if (Output is null || !Output.CanWrite) { Error = "+Quote("A writable output stream is required.")+"; return false; }",
            "        global::CSharpGameEngine.Runtime.Windows.EngineHost? EngineHost = null;",
            "        global::CSharpGameEngine.Entities.State State = default;",
            "        GeneratedSystemSet Systems = default;",
            "        bool LoopInitialized = false;",
            "        bool Succeeded = false;",
            "        try {",
            "            EngineHost = new global::CSharpGameEngine.Runtime.Windows.EngineHost();",
            "            State = EngineHost.CreateState();",
            "            bool Matched = false;",
            "            switch (SceneName) {",
        ];
        foreach(SceneEmitModel Scene in Scenes.OrderBy(static Scene=>Scene.ClassFullyQualifiedName,StringComparer.Ordinal)){
            Lines.Add($"                case {Quote(Scene.ClassFullyQualifiedName)}: State.World.InstantiateScene<global::{Scene.ClassFullyQualifiedName}>(); Matched = true; break;");
        }
        Lines.Add("            }");
        Lines.Add("            if (!Matched) { Error = "+Quote("The requested scene is not part of this compilation.")+"; }");
        Lines.Add("            else {");
        Lines.Add("                State.Enabled = true;");
        Lines.Add("                State.ExecutionMode = global::CSharpGameEngine.Entities.EngineExecutionMode.Runtime;");
        Lines.Add("                LoopInitialized = true;");
        Lines.Add("                var Identity = new global::CSharpGameEngine.Runtime.Simulation.SimulationCacheIdentity(");
        Lines.Add("                    "+Quote("physics")+", "+Quote("LogicalScalar-Q64.64")+", State.FixedTickRate, DependencyHash!,");
        Lines.Add("                    global::CSharpGameEngine.Runtime.Physics.PhysicsCacheSerializer.SchemaVersion);");
        Lines.Add("                using var Writer = new global::CSharpGameEngine.Runtime.Physics.PhysicsCacheStreamWriter(Output, Identity, TickCount);");
        Lines.Add("                for (int FrameIndex = 0; FrameIndex < TickCount; FrameIndex++) {");
        Lines.Add("                    CancellationToken.ThrowIfCancellationRequested();");
        Lines.Add("                    ulong Tick = State.FixedTick;");
        Lines.Add("                    GeneratedGameLoop.RunBakeTick(ref State, ref Systems, EngineHost);");
        Lines.Add("                    if (!State.Enabled || State.FixedTick != checked(Tick + 1UL)) {");
        Lines.Add("                        throw new global::System.InvalidOperationException("+Quote("The generated game loop stopped before the requested Bake tick completed.")+");");
        Lines.Add("                    }");
        Lines.Add("                    EngineHost.WritePhysicsCacheFrame(Writer, Tick);");
        Lines.Add("                }");
        Lines.Add("                Writer.Complete();");
        Lines.Add("                Succeeded = true;");
        Lines.Add("            }");
        Lines.Add("        } catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("            Error = Exception is global::System.OperationCanceledException");
        Lines.Add("                ? "+Quote("Physics Bake was cancelled.")+" : Exception.Message;");
        Lines.Add("        } finally {");
        Lines.Add("            if (LoopInitialized) {");
        Lines.Add("                try { GeneratedGameLoop.Shutdown(ref State, ref Systems, EngineHost!); }");
        Lines.Add("                catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("                    if (Succeeded) { Succeeded = false; Error = Exception.Message; }");
        Lines.Add("                    else if (string.IsNullOrEmpty(Error)) Error = Exception.Message;");
        Lines.Add("                }");
        Lines.Add("            }");
        Lines.Add("            try { EngineHost?.Dispose(); }");
        Lines.Add("            catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("                if (Succeeded) { Succeeded = false; Error = Exception.Message; }");
        Lines.Add("                else if (string.IsNullOrEmpty(Error)) Error = Exception.Message;");
        Lines.Add("            }");
        Lines.Add("        }");
        Lines.Add("        return Succeeded;");
        Lines.Add("    }");
        // ADR-0078/M0113：ベイク済み cache を同じ生成済み system で再生し、world が各 tick で保持する状態を再び cache に書き込みます。
        // 再生結果が bake と一致する場合、byte 列も完全に一致します。破断で生じた断片からなる同じ body が、同じ pose、
        // 同じ event とともに記録されます。
        Lines.Add("    public static bool TryReplay(");
        Lines.Add("        string? SceneName, int TickCount, string? DependencyHash, global::System.IO.Stream? Cache, global::System.IO.Stream? Output,");
        Lines.Add("        global::System.Threading.CancellationToken CancellationToken, out string Error) {");
        Lines.Add("        Error = string.Empty;");
        Lines.Add("        if (string.IsNullOrWhiteSpace(SceneName)) { Error = "+Quote("A fully-qualified scene name is required.")+"; return false; }");
        Lines.Add("        if (TickCount is < 1 or > global::CSharpGameEngine.Runtime.Physics.PhysicsCacheSerializer.MaximumFrameCount) {");
        Lines.Add("            Error = "+Quote("Tick count is outside the supported physics cache range.")+"; return false;");
        Lines.Add("        }");
        Lines.Add("        if (string.IsNullOrWhiteSpace(DependencyHash)) { Error = "+Quote("A dependency hash is required.")+"; return false; }");
        Lines.Add("        if (Cache is null || !Cache.CanRead) { Error = "+Quote("A readable cache stream is required.")+"; return false; }");
        Lines.Add("        if (Output is null || !Output.CanWrite) { Error = "+Quote("A writable output stream is required.")+"; return false; }");
        Lines.Add("        global::CSharpGameEngine.Runtime.Windows.EngineHost? EngineHost = null;");
        Lines.Add("        global::CSharpGameEngine.Entities.State State = default;");
        Lines.Add("        GeneratedSystemSet Systems = default;");
        Lines.Add("        bool LoopInitialized = false;");
        Lines.Add("        bool Succeeded = false;");
        Lines.Add("        try {");
        Lines.Add("            EngineHost = new global::CSharpGameEngine.Runtime.Windows.EngineHost();");
        Lines.Add("            State = EngineHost.CreateState();");
        Lines.Add("            bool Matched = false;");
        Lines.Add("            switch (SceneName) {");
        foreach(SceneEmitModel Scene in Scenes.OrderBy(static Scene=>Scene.ClassFullyQualifiedName,StringComparer.Ordinal)){
            Lines.Add($"                case {Quote(Scene.ClassFullyQualifiedName)}: State.World.InstantiateScene<global::{Scene.ClassFullyQualifiedName}>(); Matched = true; break;");
        }
        Lines.Add("            }");
        Lines.Add("            if (!Matched) { Error = "+Quote("The requested scene is not part of this compilation.")+"; }");
        Lines.Add("            else {");
        Lines.Add("                State.Enabled = true;");
        Lines.Add("                State.ExecutionMode = global::CSharpGameEngine.Entities.EngineExecutionMode.Runtime;");
        Lines.Add("                LoopInitialized = true;");
        Lines.Add("                var Identity = new global::CSharpGameEngine.Runtime.Simulation.SimulationCacheIdentity(");
        Lines.Add("                    "+Quote("physics")+", "+Quote("LogicalScalar-Q64.64")+", State.FixedTickRate, DependencyHash!,");
        Lines.Add("                    global::CSharpGameEngine.Runtime.Physics.PhysicsCacheSerializer.SchemaVersion);");
        Lines.Add("                if (!EngineHost.TryLoadPhysicsCache(Cache, Identity, false, out var LoadError)) { Error = LoadError; }");
        Lines.Add("                else {");
        Lines.Add("                    using var Writer = new global::CSharpGameEngine.Runtime.Physics.PhysicsCacheStreamWriter(Output, Identity, TickCount);");
        Lines.Add("                    for (int FrameIndex = 0; FrameIndex < TickCount; FrameIndex++) {");
        Lines.Add("                        CancellationToken.ThrowIfCancellationRequested();");
        Lines.Add("                        ulong Tick = State.FixedTick;");
        Lines.Add("                        GeneratedGameLoop.RunBakeTick(ref State, ref Systems, EngineHost);");
        Lines.Add("                        if (!State.Enabled || State.FixedTick != checked(Tick + 1UL)) {");
        Lines.Add("                            throw new global::System.InvalidOperationException("+Quote("The generated game loop stopped before the requested replay tick completed.")+");");
        Lines.Add("                        }");
        Lines.Add("                        if (EngineHost.PhysicsCacheState != global::CSharpGameEngine.Runtime.Physics.PhysicsCachePlaybackState.Playing) {");
        Lines.Add("                            throw new global::System.InvalidOperationException(\"The physics cache playback stopped at tick \" + Tick.ToString(global::System.Globalization.CultureInfo.InvariantCulture) + \" (\" + EngineHost.PhysicsCacheState.ToString() + \"): the world no longer matches the recorded bodies.\");");
        Lines.Add("                        }");
        Lines.Add("                        EngineHost.WritePhysicsCacheFrame(Writer, Tick);");
        Lines.Add("                    }");
        Lines.Add("                    Writer.Complete();");
        Lines.Add("                    Succeeded = true;");
        Lines.Add("                }");
        Lines.Add("            }");
        Lines.Add("        } catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("            Error = Exception is global::System.OperationCanceledException");
        Lines.Add("                ? "+Quote("Physics replay was cancelled.")+" : Exception.Message;");
        Lines.Add("        } finally {");
        Lines.Add("            if (LoopInitialized) {");
        Lines.Add("                try { GeneratedGameLoop.Shutdown(ref State, ref Systems, EngineHost!); }");
        Lines.Add("                catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("                    if (Succeeded) { Succeeded = false; Error = Exception.Message; }");
        Lines.Add("                    else if (string.IsNullOrEmpty(Error)) Error = Exception.Message;");
        Lines.Add("                }");
        Lines.Add("            }");
        Lines.Add("            try { EngineHost?.Dispose(); }");
        Lines.Add("            catch (global::System.Exception Exception) when (IsExpectedFailure(Exception)) {");
        Lines.Add("                if (Succeeded) { Succeeded = false; Error = Exception.Message; }");
        Lines.Add("                else if (string.IsNullOrEmpty(Error)) Error = Exception.Message;");
        Lines.Add("            }");
        Lines.Add("        }");
        Lines.Add("        return Succeeded;");
        Lines.Add("    }");
        Lines.Add("    private static bool IsExpectedFailure(global::System.Exception Exception) =>");
        Lines.Add("        Exception is global::System.ArgumentException");
        Lines.Add("            or global::System.InvalidOperationException");
        Lines.Add("            or global::System.IO.IOException");
        Lines.Add("            or global::System.UnauthorizedAccessException");
        Lines.Add("            or global::System.OverflowException");
        Lines.Add("            or global::System.OperationCanceledException;");
        Lines.Add("}");
        Context.AddSource(HintName,SourceText.From(string.Join(((char)10).ToString(),Lines),Encoding.UTF8));
    }

    private static string Quote(string Value)=>Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(Value,true);
}
