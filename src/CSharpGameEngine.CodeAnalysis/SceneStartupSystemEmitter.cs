using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>[StartupScene]</c>が付いた<c>IScene</c>実装から、既存の<c>GameSystemGenerator</c>パイプラインへ
/// そのまま合流できる合成<c>ISystem</c>を1つ作る(ADR-0040)。
///
/// <para>
/// Roslynの1つのGeneratorは自分自身が生成した構文木を同じ実行内で再検出できない
/// (<c>SyntaxProvider</c>は元のユーザーコンパイルしか見ない)ため、「<c>ISystem</c>を実装するstructを
/// 生成して<see cref="GameSystemAnalyzer"/>による再検出に期待する」という設計は取れない。代わりに
/// <see cref="BuildSyntheticSystemResult"/>が<see cref="GameSystemResult"/>を<b>直接構築</b>し、
/// 実際に検出された(手書きの)Systemと同じ<c>List</c>へ合流させたうえで<c>GameSystemIndexAssigner.Assign</c>
/// へ渡す。<see cref="EmitHiddenSystem"/>はその合成Systemが指す実体(隠しstruct)のソースを生成するだけで、
/// 生成された<c>GameSystem.Loop.g.cs</c>からは手書きのSystemと区別なく呼び出される。
/// </para>
///
/// <para>
/// 本体は<c>{Scene}.Instantiate(ref State.World)</c>の1行だけになった。Entityの構成を知っているのは
/// <see cref="SceneInstantiateEmitter"/>であり、ここは「起動時に1回だけ呼ぶ」という実行タイミングの
/// 責務しか持たない。
/// </para>
/// </summary>
internal static class SceneStartupSystemEmitter {
    /// <summary>合成Systemが対象とするQuery(生成されたエントリポイントが撒く唯一のシードComponent)。</summary>
    private const string BootstrapComponentFullyQualifiedName=GameSystemEntryPointEmitter.BootstrapComponentFullyQualifiedName;

    private const string StateFullyQualifiedName="global::CSharpGameEngine.Entities.State";

    private const string SystemInterfaceFullyQualifiedName="global::CSharpGameEngine.Entities.ISystem";

    /// <summary>
    /// <paramref name="Scene"/>を<c>Update(ref Bootstrap, ref State)</c>1本だけを持つ合成Systemとして
    /// モデル化する。<see cref="GameSystemIndexAssigner.Assign"/>・<see cref="GameSystemLoopEmitter"/>・
    /// <see cref="GameSystemEntryPointEmitter"/>はいずれもこの型と実際に検出されたSystemを区別しない。
    /// </summary>
    internal static GameSystemResult BuildSyntheticSystemResult(SceneEmitModel Scene){
        ImmutableArray<GameSystemComponentParameterModel>Components=[new GameSystemComponentParameterModel("Bootstrap",BootstrapComponentFullyQualifiedName)];

        ImmutableArray<GameSystemParameterSlot>CallOrder=[
            new GameSystemParameterSlot(GameSystemParameterRole.Component,0),
            new GameSystemParameterSlot(GameSystemParameterRole.State,0),
        ];

        GameSystemMethodModel Method=new(
            GameSystemMethodRole.Dispatch,
            hasLeadingEntityParameter:false,
            Components,
            contexts:[],
            CallOrder,
            Scene.DeclarationPosition);

        return new GameSystemResult(
            Scene.Namespace,
            HiddenSystemSimpleName(Scene),
            [Method],
            diagnostics:[],
            Scene.FilePath,
            Scene.DeclarationPosition);
    }

    /// <summary>
    /// <see cref="BuildSyntheticSystemResult"/>が指す隠しstructの実体を生成する。<c>Bootstrap.Done</c>で
    /// 1回だけ走ることを保証し、生成された<c>Instantiate</c>を呼ぶ。Reflection・<c>object[]</c>・Boxingは
    /// いずれも使わない。
    /// </summary>
    internal static void EmitHiddenSystem(SourceProductionContext Context,SceneEmitModel Scene){
        if(!Scene.CanEmit){
            return;
        }

        var HiddenTypeName=HiddenSystemSimpleName(Scene);
        List<string>Lines=["// <auto-generated/>","#nullable enable"];

        if(Scene.Namespace is not null){
            Lines.Add($"namespace {Scene.Namespace};");
        }

        Lines.Add($"internal struct {HiddenTypeName} : {SystemInterfaceFullyQualifiedName} {{");
        Lines.Add($"    public bool Update(ref {BootstrapComponentFullyQualifiedName} Bootstrap, ref {StateFullyQualifiedName} State) {{");
        Lines.Add("        if (Bootstrap.Done) {");
        Lines.Add("            return true;");
        Lines.Add("        }");
        Lines.Add("        Bootstrap.Done = true;");

        // State.Worldはget-onlyプロパティなのでrefを取れない。InstantiateScene<TScene>()は
        // Worldのインスタンスメソッドなのでプロパティの値に対して呼べる。Worldのフィールドはすべて
        // 参照型(ChunkBuffer/SceneInstanceTable/ArchetypeNN)なので、structのコピー越しでも
        // 同じ実体を更新する — これは既存のState.World.Create(...)と同じ仕組みである。
        Lines.Add($"        State.World.InstantiateScene<{Scene.GlobalQualifiedName}>();");
        Lines.Add("        return true;");
        Lines.Add("    }");
        Lines.Add("}");

        var HintName=Scene.Namespace is null
            ? $"{Scene.ClassName}.StartupSystem.g.cs"
            : $"{Scene.Namespace}.{Scene.ClassName}.StartupSystem.g.cs";

        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }

    private static string HiddenSystemSimpleName(SceneEmitModel Scene)=> $"{Scene.ClassName}__StartupSystem";
}
