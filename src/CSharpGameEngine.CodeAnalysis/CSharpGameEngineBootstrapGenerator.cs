using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// Wiring-verification generator for the CSharpGameEngine.CodeAnalysis foundation (ADR-0014).
/// Emits exactly one fixed, compilation-independent file via
/// <see cref="IncrementalGeneratorInitializationContext.RegisterPostInitializationOutput(System.Action{IncrementalGeneratorPostInitializationContext})"/>
/// so the Incremental Generator pipeline is proven to run without depending on, or varying by, any
/// consuming project's source. No pipeline stage reads <c>CompilationProvider</c> or
/// <c>AnalyzerConfigOptionsProvider</c>: this generator's contract is a fixed output, so consuming
/// either input would either be unused (dead code) or make the output vary per-project (breaking the
/// "identical output across builds" requirement) - the pipeline is proven end-to-end instead by the
/// generator driver tests in CSharpGameEngine.CodeAnalysis.Tests.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class CSharpGameEngineBootstrapGenerator : IIncrementalGenerator
{
    public const string GeneratedHintName = "CSharpGameEngineBootstrap.g.cs";

    /// <summary>
    /// Lines joined with "\n" rather than a multi-line string literal, so the emitted bytes are
    /// independent of this source file's own line-ending state (LF vs CRLF differs between a Windows
    /// checkout and Linux CI under autocrlf) - required for byte-identical output across builds.
    /// </summary>
    private static readonly string[] GeneratedSourceLines =
    [
        "// <auto-generated/>",
        "",
        "namespace CSharpGameEngine.Generated;",
        "",
        "internal static class CodeAnalysisBootstrap",
        "{",
        "    internal const string GeneratorName =",
        "        \"CSharpGameEngine.CodeAnalysis\";",
        "}",
        "",
    ];

    public void Initialize(IncrementalGeneratorInitializationContext Context)
    {
        Context.RegisterPostInitializationOutput(EmitBootstrapSource);
    }

    private static void EmitBootstrapSource(IncrementalGeneratorPostInitializationContext Context)
    {
        string Source = string.Join("\n", GeneratedSourceLines);
        Context.AddSource(GeneratedHintName, SourceText.From(Source, Encoding.UTF8));
    }
}
