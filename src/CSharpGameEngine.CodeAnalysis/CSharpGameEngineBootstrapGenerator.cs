using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// CSharpGameEngine.CodeAnalysis 基盤の配線を検証するジェネレーター (ADR-0014)。<see cref="IncrementalGeneratorInitializationContext.RegisterPostInitializationOutput(System.Action{IncrementalGeneratorPostInitializationContext})"/> を使い、コンパイルに依存せず、コンパイルごとに変化しない固定ファイルをちょうど 1 つ出力する。インクリメンタルジェネレーターのパイプラインが実行されることを検証し、利用側プロジェクトのソースには依存しない。パイプラインのどの段階も <c>CompilationProvider</c> または <c>AnalyzerConfigOptionsProvider</c> を読み取らない。このジェネレーターの契約は固定出力であり、いずれかの入力を消費すると未使用の処理（死んだコード）になるか、プロジェクトごとに出力が変わって「ビルド間で同一出力」という要件を破るためである。パイプライン全体の実行は、CSharpGameEngine.CodeAnalysis.Tests のジェネレータードライバーテストで別途検証する。
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class CSharpGameEngineBootstrapGenerator:IIncrementalGenerator {
    public const string GeneratedHintName="CSharpGameEngineBootstrap.g.cs";

    /// <summary>
    /// 複数行文字列リテラルではなく "\n" で行を連結する。これにより、出力バイト列はこのソースファイル自体の改行コード状態に左右されない（autocrlf により Windows のチェックアウトと Linux CI で LF/CRLF が異なる）。ビルド間でバイト単位の出力一致を求めるには必須である。
    /// </summary>
    private static readonly string[]GeneratedSourceLines=[
        "// <auto-generated/>",
        "",
        "namespace CSharpGameEngine.Generated;",
        "",
        "internal static class CodeAnalysisBootstrap",
        "{",
        "    internal const string GeneratorName =",
        "        \"CSharpGameEngine.CodeAnalysis\";",
        "}",
        "",
    ];

    public void Initialize(IncrementalGeneratorInitializationContext Context){
        Context.RegisterPostInitializationOutput(EmitBootstrapSource);
    }

    private static void EmitBootstrapSource(IncrementalGeneratorPostInitializationContext Context){
        var Source=string.Join("\n",GeneratedSourceLines);
        Context.AddSource(GeneratedHintName,SourceText.From(Source,Encoding.UTF8));
    }
}
