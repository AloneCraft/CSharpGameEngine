/// <summary>Comparable input reduced from the assembly attribute before the generator emits source.</summary>
internal readonly struct TransformPrecisionConfiguration {
    internal readonly bool IsValid;
    internal readonly int TotalBits;
    internal readonly int FractionalBits;
    internal readonly ImmutableArray<Diagnostic>Diagnostics;

    private TransformPrecisionConfiguration(bool IsValid,int TotalBits,int FractionalBits,ImmutableArray<Diagnostic>Diagnostics){
        this.IsValid=IsValid;
        this.TotalBits=TotalBits;
        this.FractionalBits=FractionalBits;
        this.Diagnostics=Diagnostics;
    }

    internal static TransformPrecisionConfiguration FromCompilation(Compilation Compilation,CancellationToken CancellationToken){
        var AttributeMetadataName=TransformPrecisionGenerator.TransformPrecisionAttributeFullyQualifiedName.Substring("global::".Length);
        var AttributeSymbol=Compilation.GetTypeByMetadataName(AttributeMetadataName);

        // This analyzer package is consumed by projects that do not use the ECS or spatial stack.
        // No attribute type means no opt-in and therefore no generated source or diagnostic.
        if(AttributeSymbol is null){
            return new TransformPrecisionConfiguration(false,0,0,ImmutableArray<Diagnostic>.Empty);
        }

        List<AttributeData>Configurations=[];

        foreach(var Attribute in Compilation.Assembly.GetAttributes()){
            if(SymbolEqualityComparer.Default.Equals(Attribute.AttributeClass,AttributeSymbol)){
                Configurations.Add(Attribute);
            }
        }

        if(Configurations.Count==0){
            return new TransformPrecisionConfiguration(false,0,0,ImmutableArray<Diagnostic>.Empty);
        }

        if(Configurations.Count!=1){
            var Location=GetLocation(Configurations[0],CancellationToken);
            return new TransformPrecisionConfiguration(
                false,
                0,
                0,
                ImmutableArray.Create(Diagnostic.Create(
                    TransformPrecisionDiagnostics.DuplicateConfiguration,
                    Location,
                    Configurations.Count)));
        }

        var Configuration=Configurations[0];
        var ConfigurationLocation=GetLocation(Configuration,CancellationToken);

        if(!TryReadArguments(Configuration,out var TotalBits,out var FractionalBits)){
            return new TransformPrecisionConfiguration(
                false,
                0,
                0,
                ImmutableArray.Create(Diagnostic.Create(
                    TransformPrecisionDiagnostics.InvalidArguments,
                    ConfigurationLocation)));
        }

        if(!IsSupportedTotalBits(TotalBits)){
            return new TransformPrecisionConfiguration(
                false,
                TotalBits,
                FractionalBits,
                ImmutableArray.Create(Diagnostic.Create(
                    TransformPrecisionDiagnostics.UnsupportedTotalBits,
                    ConfigurationLocation,
                    TotalBits)));
        }

        var MaximumFractionalBits=TotalBits-3;

        if(FractionalBits<1||FractionalBits>MaximumFractionalBits){
            return new TransformPrecisionConfiguration(
                false,
                TotalBits,
                FractionalBits,
                ImmutableArray.Create(Diagnostic.Create(
                    TransformPrecisionDiagnostics.InvalidFractionalBits,
                    ConfigurationLocation,
                    FractionalBits,
                    TotalBits,
                    MaximumFractionalBits)));
        }

        return new TransformPrecisionConfiguration(
            true,
            TotalBits,
            FractionalBits,
            ImmutableArray<Diagnostic>.Empty);
    }

    private static bool TryReadArguments(AttributeData Configuration,out int TotalBits,out int FractionalBits){
        TotalBits=0;
        FractionalBits=0;

        if(Configuration.ConstructorArguments.Length!=2
           ||Configuration.ConstructorArguments[0].Value is not int ConfiguredTotalBits
           ||Configuration.ConstructorArguments[1].Value is not int ConfiguredFractionalBits){
            return false;
        }

        TotalBits=ConfiguredTotalBits;
        FractionalBits=ConfiguredFractionalBits;
        return true;
    }

    private static Location GetLocation(AttributeData Attribute,CancellationToken CancellationToken)=>
        Attribute.ApplicationSyntaxReference?.GetSyntax(CancellationToken).GetLocation()??Location.None;

    private static bool IsSupportedTotalBits(int TotalBits){
        switch(TotalBits){
            case 64:
            case 128:
            case 192:
            case 256:
            case 320:
            case 384:
            case 448:
            case 512:
                return true;

            default:
                return false;
        }
    }
