    public static bool TryParseInvariant(string? Text,out FixedScalar Result){
        Result=default;
        if(string.IsNullOrWhiteSpace(Text)){
            return false;
        }
        string Value=Text.Trim();
        char Last=Value[Value.Length-1];
        if(Last=='f'||Last=='F'||Last=='d'||Last=='D'||Last=='m'||Last=='M'){
            Value=Value.Substring(0,Value.Length-1);
        }
        bool Negative=false;
        if(Value.StartsWith("+",global::System.StringComparison.Ordinal)){
            Value=Value.Substring(1);
        } else if(Value.StartsWith("-",global::System.StringComparison.Ordinal)){
            Negative=true;
            Value=Value.Substring(1);
        }
        int ExponentMarker=Value.IndexOfAny(new[]{'e','E'});
        int Exponent=0;
        if(ExponentMarker>=0){
            if(Value.IndexOfAny(new[]{'e','E'},ExponentMarker+1)>=0
                ||!int.TryParse(Value.Substring(ExponentMarker+1),
                    global::System.Globalization.NumberStyles.AllowLeadingSign,
                    global::System.Globalization.CultureInfo.InvariantCulture,out Exponent)){
                return false;
            }
            Value=Value.Substring(0,ExponentMarker);
        }
        int Point=Value.IndexOf('.');
        if(Point>=0&&Value.IndexOf('.',Point+1)>=0){
            return false;
        }
        string Whole=Point>=0?Value.Substring(0,Point):Value;
        string Fraction=Point>=0?Value.Substring(Point+1):string.Empty;
        if(Whole.Length==0){
            Whole="0";
        }
        string Digits=Whole+Fraction;
        if(Digits.Length==0){
            return false;
        }
        for(int Index=0;Index<Digits.Length;Index++){
            if(Digits[Index]<'0'||Digits[Index]>'9'){
                return false;
            }
        }
        if(Exponent>1024){
            return false;
        }
        if(Exponent<-1024){
            return true;
        }
        global::System.Numerics.BigInteger Significand;
        try {
            Significand=global::System.Numerics.BigInteger.Parse(Digits,
                global::System.Globalization.CultureInfo.InvariantCulture);
        } catch(global::System.FormatException) {
            return false;
        }
        int DecimalExponent=Exponent-Fraction.Length;
        global::System.Numerics.BigInteger Raw;
        if(DecimalExponent>=0){
            Raw=(Significand*global::System.Numerics.BigInteger.Pow(10,DecimalExponent))<<FractionalBits;
        } else {
            Raw=DivideRoundToNearest(Significand<<FractionalBits,
                global::System.Numerics.BigInteger.Pow(10,-DecimalExponent));
        }
        return TryFromRaw(Negative?-Raw:Raw,out Result);
    }

