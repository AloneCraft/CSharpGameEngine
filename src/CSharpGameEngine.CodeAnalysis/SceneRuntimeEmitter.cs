using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>[SceneDefinition]</c>クラスへ、<c>Define</c>の構文木から直接構築した<c>CreateRuntime</c>を追加生成
/// する。Reflection・ラムダ式の解析・<c>SceneBuilder</c>の動的解釈は一切行わず、コンパイル時に確定した
/// <c>ArchetypeNN.Create</c>の直接呼び出しだけで構成する(ADR-0033)。
///
/// <para>
/// 旧実装は<c>CreateEntity(CreateArchetype&lt;T...&gt;())</c>の後に<c>GetRef&lt;T&gt;</c>で1つずつ値を
/// 代入していたが、閉集合Archetype方式では<c>Create</c>ファクトリが全Componentの値を一括で受け取るため、
/// ノードごとに1呼び出しで済むようになった(後付け代入パスが不要になり簡潔化)。
/// </para>
///
/// <para>
/// 非Rootの子ノードには<see cref="global::CSharpGameEngine.Entities.Parent"/>を自動的に付与し、
/// <c>Set</c>呼び出しが1つも無い空ノードには<see cref="global::CSharpGameEngine.Entities.SceneNodeTag"/>を
/// 付与する(Archetypeは1個以上のComponentを必要とするため)。<c>World</c>がstructになったため
/// <c>CreateRuntime</c>は<c>ref World</c>を取る。
/// </para>
/// </summary>
internal static class SceneRuntimeEmitter
{
    private const string EntityFullyQualifiedName = "global::CSharpGameEngine.Entities.Entity";
    private const string WorldFullyQualifiedName = "global::CSharpGameEngine.Entities.World";
    internal const string ParentFullyQualifiedName = "global::CSharpGameEngine.Entities.Parent";
    internal const string SceneNodeTagFullyQualifiedName = "global::CSharpGameEngine.Entities.SceneNodeTag";

    internal static void Emit(SourceProductionContext Context, SceneDefinitionClassResult Result, GameSystemRegistry Registry)
    {
        if (Result.Diagnostics.Length > 0 || Result.Root is not { } Root)
        {
            return;
        }

        Dictionary<string, int> ComponentIndexByType = new(StringComparer.Ordinal);

        foreach (GameSystemComponentInfo Component in Registry.ComponentsByIndex)
        {
            ComponentIndexByType[Component.TypeFullyQualifiedName] = Component.Index;
        }

        List<string> Lines = ["// <auto-generated/>", "#nullable enable"];

        foreach (string UsingDirective in Result.UsingDirectives)
        {
            Lines.Add(UsingDirective);
        }

        if (Result.Namespace is not null)
        {
            Lines.Add("");
            Lines.Add($"namespace {Result.Namespace};");
        }

        Lines.Add("");
        Lines.Add($"partial class {Result.ClassName}");
        Lines.Add("{");
        Lines.Add($"    public static {EntityFullyQualifiedName} CreateRuntime(ref {WorldFullyQualifiedName} world)");
        Lines.Add("    {");

        EmitNode(Lines, Root, ParentPropertyName: null, Registry, ComponentIndexByType);

        Lines.Add($"        return {Root.PropertyName};");
        Lines.Add("    }");
        Lines.Add("}");
        Lines.Add("");

        string HintName = Result.Namespace is null
            ? $"{Result.ClassName}.SceneRuntime.g.cs"
            : $"{Result.Namespace}.{Result.ClassName}.SceneRuntime.g.cs";

        Context.AddSource(HintName, SourceText.From(string.Join("\n", Lines), Encoding.UTF8));
    }

    /// <summary>
    /// 1ノードの実効Component構成(型FQN, 初期化式)を、ソース記述順+末尾Parentという固定順で返す。
    /// Archetypeの登録(<see cref="CollectComponentSets"/>)と生成(<see cref="EmitNode"/>)が
    /// 必ず同じ集合を導出するよう、両者からこの1箇所を共有する。
    /// </summary>
    private static List<(string TypeFullyQualifiedName, string? InitializerExpressionText)> BuildEffectiveComponents(SceneNodeModel Node, string? ParentPropertyName)
    {
        List<(string, string?)> Components = [];

        if (Node.Components.Length == 0)
        {
            Components.Add((SceneNodeTagFullyQualifiedName, null));
        }
        else
        {
            foreach (ComponentSetModel Component in Node.Components)
            {
                Components.Add((Component.TypeFullyQualifiedName, Component.InitializerExpressionText));
            }
        }

        if (ParentPropertyName is not null)
        {
            Components.Add((ParentFullyQualifiedName, $"new {ParentFullyQualifiedName} {{ Value = {ParentPropertyName} }}"));
        }

        return Components;
    }

    /// <summary>
    /// Scene定義の全ノードが必要とするComponent集合を列挙する。<see cref="GameSystemIndexAssigner"/>が
    /// SystemのUpdate/Spawn形状と同じArchetype空間へ登録するために使う。
    /// </summary>
    internal static List<IReadOnlyList<string>> CollectComponentSets(SceneDefinitionClassResult Result)
    {
        List<IReadOnlyList<string>> Sets = [];

        if (Result.Diagnostics.Length > 0 || Result.Root is not { } Root)
        {
            return Sets;
        }

        void Walk(SceneNodeModel Node, string? ParentPropertyName)
        {
            Sets.Add([.. BuildEffectiveComponents(Node, ParentPropertyName).Select(static C => C.TypeFullyQualifiedName)]);

            foreach (SceneNodeModel Child in Node.Children)
            {
                Walk(Child, Node.PropertyName);
            }
        }

        Walk(Root, null);
        return Sets;
    }

    private static void EmitNode(
        List<string> Lines,
        SceneNodeModel Node,
        string? ParentPropertyName,
        GameSystemRegistry Registry,
        Dictionary<string, int> ComponentIndexByType)
    {
        bool IsRoot = ParentPropertyName is null;
        List<(string TypeFullyQualifiedName, string? InitializerExpressionText)> Components = BuildEffectiveComponents(Node, ParentPropertyName);

        Lines.Add("        // --------------------------------------------------------------------");
        Lines.Add($"        // {Node.PropertyName}");
        Lines.Add(IsRoot ? "        // Parent: (none, this is the Root)" : $"        // Parent: {ParentPropertyName}");
        Lines.Add("        // --------------------------------------------------------------------");

        GameSystemArchetypeInfo? Archetype = Registry.FindArchetype([.. Components.Select(C => ComponentIndexByType[C.TypeFullyQualifiedName])]);

        if (Archetype is not { } ArchetypeInfo)
        {
            // GameSystemIndexAssignerがScene形状も登録しているため、通常ここには到達しない。
            Lines.Add($"        // ERROR: no archetype registered for node '{Node.PropertyName}'");
            return;
        }

        // Createのパラメータ順はArchetypeの宣言順なので、初期化式もその順へ並べ替える。
        Dictionary<int, string?> InitializerByIndex = [];

        foreach ((string TypeFqn, string? Initializer) in Components)
        {
            InitializerByIndex[ComponentIndexByType[TypeFqn]] = Initializer;
        }

        string Arguments = string.Join(", ", ArchetypeInfo.ComponentIndices.Select(I => InitializerByIndex[I] ?? "default"));
        Lines.Add($"        {EntityFullyQualifiedName} {Node.PropertyName} = global::CSharpGameEngine.Entities.{ArchetypeInfo.Name}.Create(ref world, {Arguments});");
        Lines.Add("");

        foreach (SceneNodeModel Child in Node.Children)
        {
            EmitNode(Lines, Child, Node.PropertyName, Registry, ComponentIndexByType);
        }
    }
}
