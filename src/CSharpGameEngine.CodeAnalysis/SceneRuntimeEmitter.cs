using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>[SceneDefinition]</c>クラスへ、<c>Define</c>の構文木から直接構築した<c>CreateRuntime</c>を追加生成
/// する。Reflection・ラムダ式の解析・<c>SceneBuilder</c>の動的解釈は一切行わず、コンパイル時に確定した
/// <c>World.CreateArchetype</c>/<c>CreateEntity</c>/<c>GetRef</c>の直接呼び出しだけで構成する。非Rootの
/// 子ノードには<see cref="global::CSharpGameEngine.Entities.Parent"/>を自動的に付与し(ユーザーが
/// <c>Set(new Parent{...})</c>を書く必要はない)、<c>Set</c>呼び出しが1つも無い空ノードには
/// <see cref="global::CSharpGameEngine.Entities.SceneNodeTag"/>を付与する
/// (<c>World.CreateArchetype</c>に型引数0個のオーバーロードが無いため)。
///
/// <see cref="ComponentSetModel.InitializerExpressionText"/>はユーザーコードの<c>Set(...)</c>引数式
/// (<c>new Position { X = 0f }</c>等)をそのまま貼り付ける。<c>Vector3.One</c>のような非完全修飾参照を
/// 解決できるよう、<see cref="SceneDefinitionClassResult.UsingDirectives"/>(元ファイルのusingをそのまま
/// 複製したもの)を生成ファイルの先頭へ同様に複製する(意味解析による完全修飾化は行わない、Phase Aの
/// 簡略化方針)。診断が1件でもあるクラスはこのクラス分の生成を全てスキップする(既存2ジェネレータと
/// 同じ診断ゲートパターン)。
/// </summary>
internal static class SceneRuntimeEmitter
{
    private const string EntityFullyQualifiedName = "global::CSharpGameEngine.Entities.Entity";
    private const string WorldFullyQualifiedName = "global::CSharpGameEngine.Entities.World";
    private const string ParentFullyQualifiedName = "global::CSharpGameEngine.Entities.Parent";
    private const string SceneNodeTagFullyQualifiedName = "global::CSharpGameEngine.Entities.SceneNodeTag";

    internal static void Emit(SourceProductionContext context, SceneDefinitionClassResult result)
    {
        if (result.Diagnostics.Length > 0 || result.Root is not { } root)
        {
            return;
        }

        List<string> lines = ["// <auto-generated/>", "#nullable enable"];

        foreach (string usingDirective in result.UsingDirectives)
        {
            lines.Add(usingDirective);
        }

        if (result.Namespace is not null)
        {
            lines.Add("");
            lines.Add($"namespace {result.Namespace};");
        }

        lines.Add("");
        lines.Add($"partial class {result.ClassName}");
        lines.Add("{");
        lines.Add($"    public static {EntityFullyQualifiedName} CreateRuntime({WorldFullyQualifiedName} world)");
        lines.Add("    {");
        lines.Add("        global::System.ArgumentNullException.ThrowIfNull(world);");
        lines.Add("");

        EmitNode(lines, root, parentPropertyName: null);

        lines.Add($"        return {root.PropertyName};");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");

        string hintName = result.Namespace is null
            ? $"{result.ClassName}.SceneRuntime.g.cs"
            : $"{result.Namespace}.{result.ClassName}.SceneRuntime.g.cs";

        context.AddSource(hintName, SourceText.From(string.Join("\n", lines), Encoding.UTF8));
    }

    /// <summary>
    /// 1ノード分の生成: <c>CreateEntity</c>呼び出し1つと、それに続く<c>GetRef</c>代入群。非Rootノードには
    /// 末尾に<c>Parent</c>を追加し(親のEntityを指す初期化式付き)、Component型引数の並びは
    /// <c>node.Components</c>のソース記述順(決定論的)+末尾Parentという固定順になるため、
    /// 生成コードは同一入力に対して常にバイト同一になる。
    /// </summary>
    private static void EmitNode(List<string> lines, SceneNodeModel node, string? parentPropertyName)
    {
        bool isRoot = parentPropertyName is null;
        List<(string TypeFullyQualifiedName, string? InitializerExpressionText)> components = [];

        if (node.Components.Length == 0)
        {
            components.Add((SceneNodeTagFullyQualifiedName, null));
        }
        else
        {
            foreach (ComponentSetModel component in node.Components)
            {
                components.Add((component.TypeFullyQualifiedName, component.InitializerExpressionText));
            }
        }

        if (!isRoot)
        {
            components.Add((ParentFullyQualifiedName, $"new {ParentFullyQualifiedName} {{ Value = {parentPropertyName} }}"));
        }

        lines.Add("        // --------------------------------------------------------------------");
        lines.Add($"        // {node.PropertyName}");
        lines.Add(isRoot ? "        // Parent: (none, this is the Root)" : $"        // Parent: {parentPropertyName}");
        lines.Add("        // --------------------------------------------------------------------");
        lines.Add("");

        string typeArguments = string.Join(", ", components.Select(c => c.TypeFullyQualifiedName));
        lines.Add($"        {EntityFullyQualifiedName} {node.PropertyName} = world.CreateEntity(world.CreateArchetype<{typeArguments}>());");

        bool hasAnyInitializer = false;

        foreach ((string typeFullyQualifiedName, string? initializerExpressionText) in components)
        {
            if (initializerExpressionText is null)
            {
                continue;
            }

            if (!hasAnyInitializer)
            {
                lines.Add("");
            }

            hasAnyInitializer = true;
            lines.Add($"        world.GetRef<{typeFullyQualifiedName}>({node.PropertyName}) = {initializerExpressionText};");
        }

        lines.Add("");

        foreach (SceneNodeModel child in node.Children)
        {
            EmitNode(lines, child, node.PropertyName);
        }
    }
}
