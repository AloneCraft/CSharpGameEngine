using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>Archetype</c> enumと、Archetypeごとの<c>ArchetypeNN</c> structを生成する。<c>Archetype</c>は
/// Systemが1つも無くても常に出力する(<c>Runtime.cs</c>の<c>World.EntityArchetypeIndices</c>フィールドが
/// この型を前方参照しているため、空でも型自体は存在しなければならない - ADR-0032決定事項1)。
/// 各<c>ArchetypeNN</c>は明示コンストラクタ+<c>Create</c>静的ファクトリ+<c>Archetype</c>静的プロパティ+
/// publicフィールドを持つ(すべて最終サンプルに忠実、record structは使わない)。全型はグローバル
/// 名前空間・<c>internal</c>(フィールド/メンバーの一部のみ<c>public</c>)。
/// </summary>
internal static class StaticArchetypeTypesEmitter
{
    private const string HintName = "StaticArchetype.Types.g.cs";

    internal static void Emit(SourceProductionContext context, StaticArchetypeRegistry registry)
    {
        List<string> lines = ["// <auto-generated/>", "#nullable enable", ""];

        lines.Add("internal enum Archetype");
        lines.Add("{");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"    {archetype.Name},");
        }

        lines.Add("}");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.AddRange(BuildArchetypeStruct(archetype, registry));
        }

        lines.Add("");

        string source = string.Join("\n", lines);
        context.AddSource(HintName, SourceText.From(source, Encoding.UTF8));
    }

    private static List<string> BuildArchetypeStruct(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string TypeSimpleName, string FieldName)> components = BuildComponentFields(archetype, registry);
        string constructorParameters = string.Join(", ", components.Select(c => $"{c.TypeSimpleName} {c.FieldName}"));

        List<string> lines =
        [
            $"internal struct {archetype.Name}:IArchetype{{",
            $"    public {archetype.Name}(Entity Entity, {constructorParameters}){{",
            "        this.Entity     = Entity;",
        ];

        foreach ((string _, string fieldName) in components)
        {
            lines.Add($"        this.{fieldName} = {fieldName};");
        }

        lines.Add("    }");
        lines.Add($"    public static void Create(ref World World, {constructorParameters}){{");
        lines.Add("        var Entity = new Entity(World.EntityArchetypeIndices.Count);");
        lines.Add($"        World.EntityArchetypeIndices.Add((Entity,Archetype.{archetype.Name},World.{archetype.ListFieldName}.Count));");

        string createArguments = string.Join(", ", new[] { "Entity" }.Concat(components.Select(c => c.FieldName)));
        lines.Add($"        World.{archetype.ListFieldName}.Add(new {archetype.Name}({createArguments}));");
        lines.Add("    }");
        lines.Add($"    public static Archetype Archetype => Archetype.{archetype.Name};");
        lines.Add("    public Entity     Entity    ;");

        foreach ((string typeSimpleName, string fieldName) in components)
        {
            lines.Add($"    public {typeSimpleName} {fieldName};");
        }

        lines.Add("}");

        return lines;
    }

    private static List<(string TypeSimpleName, string FieldName)> BuildComponentFields(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string, string)> components = [];

        foreach (int componentIndex in archetype.ComponentIndices)
        {
            string typeFqn = registry.ComponentsByIndex[componentIndex].TypeFullyQualifiedName;
            string simpleName = ExtractSimpleTypeName(typeFqn);
            components.Add((simpleName, simpleName));
        }

        return components;
    }

    internal static string ExtractSimpleTypeName(string typeFullyQualifiedName)
    {
        const string GlobalPrefix = "global::";
        string value = typeFullyQualifiedName.StartsWith(GlobalPrefix, StringComparison.Ordinal)
            ? typeFullyQualifiedName.Substring(GlobalPrefix.Length)
            : typeFullyQualifiedName;

        int lastDot = value.LastIndexOf('.');
        return lastDot >= 0 ? value.Substring(lastDot + 1) : value;
    }
}
