using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>MoveCommandHeader</c>+Archetypeごとの<c>MoveToArchetypeNNCommand</c>と、<c>partial struct
/// World</c>の拡張(<c>ListArchetypeNN</c>フィールド・<c>MoveArchetype</c>オーバーロード・
/// <c>Detach</c>・<c>PlaybackMoveArchetypes</c>・<c>ApplyMoveArchetypeNN</c>)を生成する。
/// <c>Runtime.cs</c>の<c>partial struct World</c>と同一コンパイル内で合成される必要があるため
/// (ADR-0032決定事項1)。<c>World</c>のもう一方の宣言(<c>Runtime.cs</c>)はフィールド初期化子
/// (<c>EntityArchetypeIndices = new()</c>)を持ち、フィールド初期化子を持つstructは明示的に宣言された
/// コンストラクターをpartialの構成全体で1つ持たなければならない(CS8983)。そのため、Archetypeが
/// 1つも無くても<c>internal partial struct World(){ }</c>(空の主コンストラクター)だけは常に出力する
/// (これがGameSystemGeneratorに無い特殊事情 - CSharpGameEngine.Entities.Worldはフィールド初期化子を
/// 使っていないため、本Generatorだけがこの制約に当たる)。
/// </summary>
internal static class StaticArchetypeWorldEmitter
{
    private const string HintName = "StaticArchetype.World.g.cs";

    internal static void Emit(SourceProductionContext context, StaticArchetypeRegistry registry)
    {
        List<string> lines = ["// <auto-generated/>", "#nullable enable", ""];

        if (registry.Archetypes.Length == 0)
        {
            lines.Add("internal partial struct World(){");
            lines.Add("}");
            lines.Add("");

            context.AddSource(HintName, SourceText.From(string.Join("\n", lines), Encoding.UTF8));
            return;
        }

        lines.Add("internal struct MoveCommandHeader(Entity Entity, Archetype Destination, int PayloadIndex){");
        lines.Add("    public Entity    Entity      = Entity;");
        lines.Add("    public Archetype Destination = Destination;");
        lines.Add("    public int       PayloadIndex= PayloadIndex;");
        lines.Add("}");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.AddRange(BuildMoveCommandStruct(archetype, registry));
        }

        lines.Add("internal partial struct World(){");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"    internal readonly ChunkList<{archetype.Name}> {archetype.ListFieldName} = new();");
        }

        lines.Add("");
        lines.Add("    internal readonly ChunkList<MoveCommandHeader> MoveCommands = new();");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"    internal readonly ChunkList<{MoveCommandTypeName(archetype)}> {MoveCommandsFieldName(archetype)} = new();");
        }

        lines.AddRange(BuildDetach(registry));

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.AddRange(BuildMoveArchetypeOverload(archetype, registry));
        }

        lines.AddRange(BuildPlaybackMoveArchetypes(registry));

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.AddRange(BuildApplyMoveArchetype(archetype, registry));
        }

        lines.Add("}");
        lines.Add("");

        string source = string.Join("\n", lines);
        context.AddSource(HintName, SourceText.From(source, Encoding.UTF8));
    }

    private static string MoveCommandTypeName(StaticArchetypeArchetypeInfo archetype) => $"MoveTo{archetype.Name}Command";

    private static string MoveCommandsFieldName(StaticArchetypeArchetypeInfo archetype) => $"MoveTo{archetype.Name}Commands";

    private static List<(string TypeSimpleName, string FieldName)> BuildComponentFields(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string, string)> components = [];

        foreach (int componentIndex in archetype.ComponentIndices)
        {
            string simpleName = StaticArchetypeTypesEmitter.ExtractSimpleTypeName(registry.ComponentsByIndex[componentIndex].TypeFullyQualifiedName);
            components.Add((simpleName, simpleName));
        }

        return components;
    }

    private static List<string> BuildMoveCommandStruct(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string TypeSimpleName, string FieldName)> components = BuildComponentFields(archetype, registry);
        string parameters = string.Join(", ", components.Select(c => $"{c.TypeSimpleName} {c.FieldName}"));

        List<string> lines =
        [
            $"internal struct {MoveCommandTypeName(archetype)}(Entity Entity, {parameters}){{",
            "    public Entity     Entity     = Entity;",
        ];

        foreach ((string typeSimpleName, string fieldName) in components)
        {
            lines.Add($"    public {typeSimpleName} {fieldName} = {fieldName};");
        }

        lines.Add("}");

        return lines;
    }

    private static List<string> BuildDetach(StaticArchetypeRegistry registry)
    {
        List<string> lines =
        [
            "    private void Detach(Entity Entity){",
            "        ref var EntityArchetypeIndex = ref this.EntityArchetypeIndices[Entity.Id];",
            "        var Index = EntityArchetypeIndex.Index;",
            "        switch (EntityArchetypeIndex.Archetype){",
        ];

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"            case Archetype.{archetype.Name}:{{");
            lines.Add($"                if(this.{archetype.ListFieldName}.RemoveAtSwapBack(Index,out var Moved)){{");
            lines.Add("                    this.EntityArchetypeIndices[Moved.Entity.Id].Index=Index;");
            lines.Add("                }");
            lines.Add("                break;");
            lines.Add("            }");
        }

        lines.Add("            default: throw new global::System.ArgumentOutOfRangeException();");
        lines.Add("        }");
        lines.Add("    }");

        return lines;
    }

    private static List<string> BuildMoveArchetypeOverload(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string TypeSimpleName, string FieldName)> components = BuildComponentFields(archetype, registry);
        string parameters = string.Join(", ", components.Select(c => $"{c.TypeSimpleName} {c.FieldName}"));
        string newArguments = string.Join(", ", new[] { "Entity" }.Concat(components.Select(c => c.FieldName)));

        return
        [
            $"    public bool MoveArchetype(Entity Entity,{parameters},ref State State){{",
            $"        var PayloadIndex = this.{MoveCommandsFieldName(archetype)}.Count;",
            $"        this.{MoveCommandsFieldName(archetype)}.Add(new({newArguments}));",
            $"        this.MoveCommands.Add(new(Entity, Archetype.{archetype.Name}, PayloadIndex));",
            "        return true;",
            "    }",
        ];
    }

    private static List<string> BuildPlaybackMoveArchetypes(StaticArchetypeRegistry registry)
    {
        List<string> lines =
        [
            "    public void PlaybackMoveArchetypes(ref State State){",
            "        for (var Index = 0; Index < this.MoveCommands.Count; Index++){",
            "            var Command = this.MoveCommands[Index];",
            "            switch (Command.Destination){",
        ];

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"                case Archetype.{archetype.Name}:");
            lines.Add($"                    this.ApplyMove{archetype.Name}(in this.{MoveCommandsFieldName(archetype)}[Command.PayloadIndex]);");
            lines.Add("                    break;");
        }

        lines.Add("                default:");
        lines.Add("                    throw new global::System.ArgumentOutOfRangeException();");
        lines.Add("            }");
        lines.Add("        }");
        lines.Add("");
        lines.Add("        this.MoveCommands.Clear();");

        foreach (StaticArchetypeArchetypeInfo archetype in registry.Archetypes)
        {
            lines.Add($"        this.{MoveCommandsFieldName(archetype)}.Clear();");
        }

        lines.Add("    }");

        return lines;
    }

    private static List<string> BuildApplyMoveArchetype(StaticArchetypeArchetypeInfo archetype, StaticArchetypeRegistry registry)
    {
        List<(string TypeSimpleName, string FieldName)> components = BuildComponentFields(archetype, registry);
        string newArguments = string.Join(", ", new[] { "Command.Entity" }.Concat(components.Select(c => $"Command.{c.FieldName}")));

        return
        [
            $"    private void ApplyMove{archetype.Name}(in {MoveCommandTypeName(archetype)} Command){{",
            "        this.Detach(Command.Entity);",
            "",
            $"        var Index = this.{archetype.ListFieldName}.Count;",
            "",
            $"        this.{archetype.ListFieldName}.Add(new({newArguments}));",
            "",
            $"        this.EntityArchetypeIndices[Command.Entity.Id] = (Command.Entity, Archetype.{archetype.Name}, Index);",
            "    }",
        ];
    }
}
