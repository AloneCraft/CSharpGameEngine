using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <see cref="EcsArchetypeAnalysisResult"/>から、アーキタイプのpartial実装・
/// <c>IEcsArchetype&lt;T&gt;</c>静的メンバー・マーカーインターフェース・名前付き引数版ファクトリを生成する。
/// 診断が1件でもあるアーキタイプはソースを生成せず、診断の報告のみ行う
/// (壊れた部分実装による二次的なコンパイルエラーを避けるため)。
/// </summary>
internal static class EcsArchetypeEmitter
{
    internal static void Emit(SourceProductionContext context, EcsArchetypeAnalysisResult result)
    {
        foreach (Diagnostic diagnostic in result.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic);
        }

        if (result.Diagnostics.Length > 0)
        {
            return;
        }

        string hintName = result.Namespace is null
            ? $"{result.StructName}.g.cs"
            : $"{result.Namespace}.{result.StructName}.g.cs";

        string source = string.Join("\n", BuildSourceLines(result));
        context.AddSource(hintName, SourceText.From(source, Encoding.UTF8));
    }

    private static List<string> BuildSourceLines(EcsArchetypeAnalysisResult result)
    {
        List<string> lines = ["// <auto-generated/>"];

        if (result.Namespace is not null)
        {
            lines.Add("");
            lines.Add($"namespace {result.Namespace};");
        }

        lines.Add("");
        lines.Add($"partial struct {result.StructName} : global::CSharpGameEngine.Ecs.IEcsArchetype<{result.StructName}>, {result.StructName}.IMarker");
        lines.Add("{");
        lines.Add("    private readonly global::CSharpGameEngine.Ecs.World world;");
        lines.Add("    private readonly global::CSharpGameEngine.Ecs.Entity entity;");
        lines.Add("");
        lines.Add($"    private {result.StructName}(global::CSharpGameEngine.Ecs.World world, global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add("        this.world = world;");
        lines.Add("        this.entity = entity;");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public global::CSharpGameEngine.Ecs.Entity Entity => this.entity;");

        for (int i = 0; i < result.NormalizedProperties.Length; i++)
        {
            EcsComponentPropertyModel property = result.NormalizedProperties[i];
            string refKeyword = property.IsReadOnly ? "ref readonly" : "ref";
            lines.Add("");
            lines.Add($"    public partial {refKeyword} {property.ComponentTypeFullyQualifiedName} {property.PropertyName}");
            lines.Add("    {");
            lines.Add($"        get {{ return ref this.world.GetComponentRef<{property.ComponentTypeFullyQualifiedName}>(this.entity, {i}); }}");
            lines.Add("    }");
        }

        lines.Add("");
        lines.Add("    public static global::System.Type[] ComponentTypes { get; } = new global::System.Type[]");
        lines.Add("    {");

        foreach (EcsComponentPropertyModel property in result.NormalizedProperties)
        {
            lines.Add($"        typeof({property.ComponentTypeFullyQualifiedName}),");
        }

        lines.Add("    };");
        lines.Add("");
        lines.Add("    public static global::CSharpGameEngine.Ecs.IComponentColumn[] CreateColumns()");
        lines.Add("    {");
        lines.Add("        return new global::CSharpGameEngine.Ecs.IComponentColumn[]");
        lines.Add("        {");

        foreach (EcsComponentPropertyModel property in result.NormalizedProperties)
        {
            lines.Add($"            new global::CSharpGameEngine.Ecs.ComponentColumn<{property.ComponentTypeFullyQualifiedName}>(),");
        }

        lines.Add("        };");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    public static {result.StructName} CreateView(global::CSharpGameEngine.Ecs.World world, global::CSharpGameEngine.Ecs.Entity entity)");
        lines.Add("    {");
        lines.Add($"        return new {result.StructName}(world, entity);");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    public interface IMarker");
        lines.Add("    {");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");
        lines.Add($"public static class {result.StructName}EcsFactory");
        lines.Add("{");

        string parameterList = string.Join(", ", result.NormalizedProperties.Select(p => $"{p.ComponentTypeFullyQualifiedName} {p.ParameterName}"));
        lines.Add($"    public static T Create<T>(this global::CSharpGameEngine.Ecs.World world, {parameterList})");
        lines.Add($"        where T : struct, global::CSharpGameEngine.Ecs.IEcsArchetype<T>, {result.StructName}.IMarker");
        lines.Add("    {");
        lines.Add("        global::CSharpGameEngine.Ecs.Entity entity = world.CreateEntityCore<T>();");

        for (int i = 0; i < result.NormalizedProperties.Length; i++)
        {
            EcsComponentPropertyModel property = result.NormalizedProperties[i];
            lines.Add($"        world.GetComponentRef<{property.ComponentTypeFullyQualifiedName}>(entity, {i}) = {property.ParameterName};");
        }

        lines.Add("        return T.CreateView(world, entity);");
        lines.Add("    }");
        lines.Add("}");
        lines.Add("");

        return lines;
    }
}
