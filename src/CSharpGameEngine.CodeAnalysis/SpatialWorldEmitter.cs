using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
namespace CSharpGameEngine.CodeAnalysis;
/// <summary>Emits the archetype-complete fixed-point global spatial-index synchronization pass.</summary>
internal static class SpatialWorldEmitter {
    private const string HintName="SpatialWorld.g.cs";
    private const string SpatialBoundsFullyQualifiedName="global::CSharpGameEngine.Entities.SpatialBounds";
    private const string TransformFullyQualifiedName="global::CSharpGameEngine.Entities.Transform";
    private const string ParentFullyQualifiedName="global::CSharpGameEngine.Entities.Parent";
    internal static bool ShouldEmit(GameSystemRegistry Registry)=>FindComponentIndex(Registry,SpatialBoundsFullyQualifiedName)>=0
        &&FindComponentIndex(Registry,TransformFullyQualifiedName)>=0
        &&Registry.Archetypes.Any(Archetype=>Archetype.ComponentIndices.Contains(FindComponentIndex(Registry,SpatialBoundsFullyQualifiedName))
            &&Archetype.ComponentIndices.Contains(FindComponentIndex(Registry,TransformFullyQualifiedName)));
    internal static void Emit(SourceProductionContext Context,GameSystemRegistry Registry){
        if(!ShouldEmit(Registry)){
            return;
        }
        int SpatialBoundsIndex=FindComponentIndex(Registry,SpatialBoundsFullyQualifiedName);
        int TransformIndex=FindComponentIndex(Registry,TransformFullyQualifiedName);
        int ParentIndex=FindComponentIndex(Registry,ParentFullyQualifiedName);
        string SpatialBoundsField=Registry.ComponentsByIndex[SpatialBoundsIndex].FieldName;
        List<string>Lines=[
            "// <auto-generated/>",
            "#nullable enable",
            "namespace CSharpGameEngine.Entities;",
            "public partial struct World {",
            "    partial void SynchronizeGlobalSpatialIndexCore() {",
            "        var World = this;",
        ];
        foreach(GameSystemArchetypeInfo Archetype in Registry.Archetypes){
            if(!Archetype.ComponentIndices.Contains(SpatialBoundsIndex)||!Archetype.ComponentIndices.Contains(TransformIndex)){
                continue;
            }
            Lines.Add($"        for (int Index = 0; Index < this.{Archetype.Name}.Count; Index++) {{");
            Lines.Add($"            this.SynchronizeGlobalSpatialEntity(this.{Archetype.Name}.GetEntityRefUnchecked(Index), this.{Archetype.Name}.Get{SpatialBoundsField}RefUnchecked(Index),");
            Lines.Add($"                (int EntityId, out {TransformFullyQualifiedName} Transform) => {{");
            Lines.Add("                    Entity Candidate = new(EntityId);");
            Lines.Add("                    if (World.TryGetComponent(Candidate, out Transform)) return true;");
            Lines.Add("                    SceneInstance OwningScene = World.GetOwningScene(Candidate);");
            Lines.Add("                    if (World.IsAlive(Candidate) && !OwningScene.IsNone && World.GetSceneRoot(OwningScene).Equals(Candidate)) {");
            Lines.Add($"                        Transform = new {TransformFullyQualifiedName}();");
            Lines.Add("                        return true;");
            Lines.Add("                    }");
            Lines.Add("                    Transform = default;");
            Lines.Add("                    return false;");
            Lines.Add("                },");
            if(ParentIndex>=0){
                Lines.Add($"                (int EntityId, out int ParentEntityId) => {{ if (World.TryGetComponent(new Entity(EntityId), out {ParentFullyQualifiedName} Parent)) {{ ParentEntityId = Parent.Value.Id; return true; }} ParentEntityId = default; return false; }});");
            } else {
                Lines.Add("                (int EntityId, out int ParentEntityId) => { ParentEntityId = default; return false; });");
            }
            Lines.Add("        }");
        }
        Lines.Add("    }");
        Lines.Add("}");
        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }
    private static int FindComponentIndex(GameSystemRegistry Registry,string FullyQualifiedName){
        for(int Index=0;Index<Registry.ComponentsByIndex.Length;Index++){
            if(Registry.ComponentsByIndex[Index].TypeFullyQualifiedName==FullyQualifiedName){
                return Index;
            }
        }
        return -1;
    }
}
