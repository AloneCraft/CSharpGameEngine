using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>[StartupScene]</c>の解析結果(<see cref="StartupSceneClassResult"/>)から、既存の<c>GameSystemGenerator</c>
/// パイプラインへそのまま合流できる合成<c>ISystem</c>を1つ作る。
///
/// <para>
/// Roslynの1つのGeneratorは自分自身が生成した構文木を同じ実行内で再検出できない
/// (<c>SyntaxProvider</c>は元のユーザーコンパイルしか見ない)ため、「<c>ISystem</c>を実装するstructを
/// 生成して<see cref="GameSystemAnalyzer"/>による再検出に期待する」という設計は取れない。代わりに
/// <see cref="BuildSyntheticSystemResult"/>が<see cref="GameSystemResult"/>を<b>直接構築</b>し、
/// 実際に検出された(手書きの)Systemと同じ<c>List</c>へ合流させたうえで<c>GameSystemIndexAssigner.Assign</c>
/// へ渡す。<see cref="EmitHiddenSystem"/>はその合成Systemが指す実体(隠しstruct)のソースを生成するだけで、
/// 生成された<c>GameSystem.Loop.g.cs</c>からは手書きのSystemと区別なく<c>new Hidden().Update(...)</c>の形で
/// 呼び出される。
/// </para>
/// </summary>
internal static class StartupSceneSystemEmitter {
    /// <summary>合成Systemが対象とするQuery(生成されたエントリポイントが撒く唯一のシードComponent)。</summary>
    private const string BootstrapComponentFullyQualifiedName=GameSystemEntryPointEmitter.BootstrapComponentFullyQualifiedName;

    private const string StateFullyQualifiedName="global::CSharpGameEngine.Entities.State";

    private const string SystemInterfaceFullyQualifiedName="global::CSharpGameEngine.Entities.ISystem";

    /// <summary>
    /// <paramref name="Scene"/>を<c>Update(ref Bootstrap, ref State)</c>1本だけを持つ合成Systemとして
    /// モデル化する。<see cref="GameSystemIndexAssigner.Assign"/>・<see cref="GameSystemLoopEmitter"/>・
    /// <see cref="GameSystemEntryPointEmitter"/>はいずれもこの型と実際に検出されたSystemを区別しない。
    /// </summary>
    internal static GameSystemResult BuildSyntheticSystemResult(StartupSceneClassResult Scene){
        ImmutableArray<GameSystemComponentParameterModel>Components=[new GameSystemComponentParameterModel("Bootstrap",BootstrapComponentFullyQualifiedName)];

        ImmutableArray<GameSystemParameterSlot>CallOrder=[
            new GameSystemParameterSlot(GameSystemParameterRole.Component,0),
            new GameSystemParameterSlot(GameSystemParameterRole.State,0),
        ];

        GameSystemMethodModel Method=new(
            GameSystemMethodRole.Dispatch,
            hasLeadingEntityParameter:false,
            Components,
            contexts:[],
            CallOrder,
            Scene.DeclarationPosition);

        return new GameSystemResult(
            Scene.Namespace,
            HiddenSystemSimpleName(Scene),
            [Method],
            diagnostics:[],
            Scene.FilePath,
            Scene.DeclarationPosition);
    }

    /// <summary>
    /// このSceneが撒く各Entityの実効Component集合。<see cref="GameSystemIndexAssigner.Assign"/>の
    /// <c>AdditionalComponentSets</c>へ追加する(既存Systemが同じ集合を先に登録済みなら重複排除される
    /// ため、Archetypeの出現順は動かない — ADR-0033のRegisterSet設計を参照)。
    /// </summary>
    internal static List<IReadOnlyList<string>>CollectComponentSets(StartupSceneClassResult Scene){
        List<IReadOnlyList<string>>Sets=[];

        if(Scene.Diagnostics.Length>0){
            return Sets;
        }

        foreach(StartupSceneEntityModel Entity in Scene.Entities){
            Sets.Add([.. Entity.Components.Select(static C=>C.TypeFullyQualifiedName)]);
        }

        return Sets;
    }

    /// <summary>
    /// <see cref="BuildSyntheticSystemResult"/>が指す隠しstructの実体を生成する。中身は旧
    /// <c>GameStartup : ISystem</c>と同じ意味(<c>Bootstrap.Done</c>判定 → 各Scene Entityプロパティを
    /// 1回だけ評価 → <c>state.World.Create(...)</c>)。Reflection・object[]・Boxingはいずれも使わない
    /// (生成されるのは通常の直接呼び出しコード)。
    /// </summary>
    internal static void EmitHiddenSystem(SourceProductionContext Context,StartupSceneClassResult Scene){
        if(Scene.Diagnostics.Length>0){
            return;
        }

        var HiddenTypeName=HiddenSystemSimpleName(Scene);
        HashSet<string>UsedLocalNames=new(StringComparer.Ordinal);

        List<string>Lines=["// <auto-generated/>","#nullable enable"];

        if(Scene.Namespace is not null){
            Lines.Add($"namespace {Scene.Namespace};");
        }

        Lines.Add($"internal struct {HiddenTypeName} : {SystemInterfaceFullyQualifiedName} {{");
        Lines.Add($"    public bool Update(ref {BootstrapComponentFullyQualifiedName} Bootstrap, ref {StateFullyQualifiedName} State) {{");
        Lines.Add("        if (Bootstrap.Done) {");
        Lines.Add("            return true;");
        Lines.Add("        }");
        Lines.Add("        Bootstrap.Done = true;");

        foreach(StartupSceneEntityModel Entity in Scene.Entities){
            Lines.AddRange(BuildEntityCreationLines(Scene,Entity,UsedLocalNames));
        }

        Lines.Add("        return true;");
        Lines.Add("    }");
        Lines.Add("}");

        var HintName=Scene.Namespace is null
            ? $"{Scene.ClassName}.StartupSystem.g.cs"
            : $"{Scene.Namespace}.{Scene.ClassName}.StartupSystem.g.cs";

        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }

    private static List<string>BuildEntityCreationLines(StartupSceneClassResult Scene,StartupSceneEntityModel Entity,HashSet<string>UsedLocalNames){
        var PropertyAccess= $"{Scene.GlobalQualifiedName}.{Entity.PropertyName}";

        // 単一Componentの戻り値はそのままCreateへ渡せば1回の評価で済む(ローカル変数は不要)。
        // Tupleの場合は各要素へ複数回アクセスする必要があるため、ローカル変数へ1回だけ格納してから
        // 各要素を読む(「プロパティは1回だけ評価する」という要件はどちらの経路でも満たされる)。
        if(Entity.Components.Length==1&&Entity.Components[0].TupleElementName is null){
            return[$"        State.World.Create({PropertyAccess});"];
        }

        var LocalName=GameSystemLoopEmitter.BuildLocalName(Entity.PropertyName,UsedLocalNames);
        var Arguments=string.Join(", ",Entity.Components.Select(C=> $"{LocalName}.{C.TupleElementName}"));

        return
        [
            $"        var {LocalName} = {PropertyAccess};",
            $"        State.World.Create({Arguments});",
        ];
    }

    private static string HiddenSystemSimpleName(StartupSceneClassResult Scene)=> $"{Scene.ClassName}__StartupSystem";
}
