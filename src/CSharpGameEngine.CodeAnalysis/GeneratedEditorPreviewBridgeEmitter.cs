using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

internal static class GeneratedEditorPreviewBridgeEmitter {
    private const string HintName="GameSystem.EditorPreviewBridge.g.cs";
    internal static void Emit(SourceProductionContext Context,IReadOnlyList<SceneEmitModel> Scenes,GameSystemRegistry Registry){
        if(Scenes.Count==0){
            return;
        }
        var HasEditorSystems=Registry.ValidSystems.Any(static S=>S.ExecuteInEditor&&S.Methods.Any(static M=>M.Role==GameSystemMethodRole.Dispatch));
        var HasRealtimeSystems=Registry.ValidSystems.Any(static S=>S.ExecuteInEditor&&S.RealtimeInEditor&&S.Methods.Any(static M=>M.Role==GameSystemMethodRole.Dispatch));
        var HasSpatialIndex=SpatialWorldEmitter.ShouldEmit(Registry);
        var HasEngineHost=Registry.ValidSystems.SelectMany(static S=>S.Methods)
            .SelectMany(static M=>M.Contexts)
            .Any(static C=>C.TypeFullyQualifiedName=="global::CSharpGameEngine.Runtime.Windows.EngineHost");
        string HostArgument=HasEngineHost?", PreviewEngineHost!":string.Empty;
        string PreviewWorldExpression=HasEngineHost?"PreviewState.World":"PreviewWorld";
        List<string> Lines=[
            "// <auto-generated/>",
            "#nullable enable",
            "namespace CSharpGameEngine.Generated;",
            "internal static class GeneratedEditorPreviewBridge {",
            "    private static global::CSharpGameEngine.Entities.World PreviewWorld;",
            "    private static global::CSharpGameEngine.Entities.State PreviewState;",
            "    private static GeneratedSystemSet PreviewSystems;",
            "    private static bool Initialized;",
            "    internal static string SelectedLogicalSpatialProfile => \"LogicalScalar-Q64.64\";",
            "    internal static bool Initialize(string? SceneName) {",
            "        PreviewWorld = new global::CSharpGameEngine.Entities.World();",
            "        PreviewSystems = default;",
            "        bool Matched = false;",
            "        switch (SceneName) {",
        ];
        if(HasEngineHost){
            int PreviewWorldFieldIndex=Lines.IndexOf("    private static global::CSharpGameEngine.Entities.World PreviewWorld;");
            Lines[PreviewWorldFieldIndex]="    private static global::CSharpGameEngine.Runtime.Windows.EngineHost? PreviewEngineHost;";
        }
        int PreviewWorldIndex=Lines.IndexOf("        PreviewWorld = new global::CSharpGameEngine.Entities.World();");
        Lines.Insert(PreviewWorldIndex,"        if (Initialized) Shutdown();");
        if(HasEngineHost){
            Lines.Insert(PreviewWorldIndex+1,"        PreviewEngineHost = new global::CSharpGameEngine.Runtime.Windows.EngineHost();");
            Lines.Insert(PreviewWorldIndex+2,"        try {");
            Lines[PreviewWorldIndex+3]="        PreviewState = PreviewEngineHost.CreateState();";
        }
        var OrderedScenes=Scenes.OrderBy(static S=>S.ClassFullyQualifiedName,StringComparer.Ordinal);
        foreach(var Scene in OrderedScenes){
            Lines.Add($"            case \"{Escape(Scene.ClassFullyQualifiedName)}\": {PreviewWorldExpression}.InstantiateScene<global::{Scene.ClassFullyQualifiedName}>(); Matched = true; break;");
        }
        Lines.Add("            default:");
        Lines.Add("                if (SceneName is null) {");
        if(OrderedScenes.FirstOrDefault() is { } DefaultScene){
            Lines.Add($"                    {PreviewWorldExpression}.InstantiateScene<global::{DefaultScene.ClassFullyQualifiedName}>(); Matched = true; break;");
        }
        Lines.Add("                }");
        Lines.Add("                break;");
        Lines.Add("        }");
        if(HasEngineHost){
            Lines.Add("        if (!Matched) { PreviewEngineHost.Dispose(); PreviewEngineHost = null; return false; }");
        } else {
            Lines.Add("        if (!Matched) return false;");
        }
        if(HasEngineHost){
            Lines.Add("        PreviewState.Enabled = true;");
            Lines.Add("        PreviewState.ExecutionMode = global::CSharpGameEngine.Entities.EngineExecutionMode.EditorPreview;");
        } else {
            Lines.Add("        PreviewState = new global::CSharpGameEngine.Entities.State(PreviewWorld) { Enabled = true, ExecutionMode = global::CSharpGameEngine.Entities.EngineExecutionMode.EditorPreview };");
        }
        if(HasEditorSystems){
            Lines.Add($"        GeneratedGameLoop.RunEditorFrame(ref PreviewState, ref PreviewSystems{HostArgument});");
        } else {
            Lines.Add("        PreviewState.World.PlaybackStructuralChanges(ref PreviewState);");
            if(HasSpatialIndex){ Lines.Add("        PreviewState.World.RefreshGlobalSpatialIndex();"); }
        }
        Lines.Add("        Initialized = true;");
        Lines.Add("        return true;");
        if(HasEngineHost){
            Lines.Add("        } catch {");
            Lines.Add("            PreviewEngineHost?.Dispose();");
            Lines.Add("            PreviewEngineHost = null;");
            Lines.Add("            PreviewState.Enabled = false;");
            Lines.Add("            throw;");
            Lines.Add("        }");
        }
        Lines.Add("    }");
        Lines.Add("    internal static void TickOnChange() {");
        Lines.Add("        if (!Initialized || !PreviewState.Enabled) return;");
        if(HasEditorSystems){
            Lines.Add($"        GeneratedGameLoop.RunEditorFrame(ref PreviewState, ref PreviewSystems{HostArgument});");
        } else {
            if(HasSpatialIndex){ Lines.Add("        PreviewState.World.RefreshGlobalSpatialIndex();"); }
        }
        Lines.Add("    }");
        if(HasRealtimeSystems){
            Lines.Add("    internal static void TickRealtime() {");
            Lines.Add("        if (!Initialized || !PreviewState.Enabled) return;");
            Lines.Add($"        GeneratedGameLoop.RunEditorRealtimeFrame(ref PreviewState, ref PreviewSystems{HostArgument});");
            Lines.Add("    }");
        } else {
            Lines.Add("    internal static void TickRealtime() { }");
        }
        Lines.Add("    internal static void Shutdown() {");
        if(HasEditorSystems){
            Lines.Add($"        if (Initialized) GeneratedGameLoop.ShutdownEditor(ref PreviewState, ref PreviewSystems{HostArgument});");
        }
        if(HasEngineHost){
            Lines.Add("        PreviewEngineHost?.Dispose();");
            Lines.Add("        PreviewEngineHost = null;");
        }
        Lines.Add("        PreviewState.Enabled = false;");
        Lines.Add("        Initialized = false;");
        Lines.Add("    }");
        Lines.Add("}");
        Context.AddSource(HintName,SourceText.From(string.Join("\n",Lines),Encoding.UTF8));
    }
    private static string Escape(string Value)=>Value.Replace("\\","\\\\").Replace("\"","\\\"");
}
