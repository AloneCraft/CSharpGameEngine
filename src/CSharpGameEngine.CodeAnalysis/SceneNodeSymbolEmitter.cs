using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CSharpGameEngine.CodeAnalysis;

/// <summary>
/// <c>[SceneDefinition]</c>クラスが宣言する各<c>private static partial SceneNodeSymbol</c>プロパティの
/// 実装本体を生成する。<see cref="SceneNodeModel.NodeId"/>は<see cref="SceneDefinitionAnalyzer"/>が
/// プロパティの完全修飾シンボル名から決定論的に導出した値をそのまま埋め込む(ユーザーは直接書かない)。
/// 診断が1件でもあるクラスはこのクラス分の生成を全てスキップする(既存2ジェネレータと同じ診断ゲート
/// パターン)。
/// </summary>
internal static class SceneNodeSymbolEmitter
{
    internal static void Emit(SourceProductionContext Context, SceneDefinitionClassResult Result)
    {
        if (Result.Diagnostics.Length > 0 || Result.Root is not { } Root)
        {
            return;
        }

        List<string> Lines = ["// <auto-generated/>", "#nullable enable"];

        if (Result.Namespace is not null)
        {
            Lines.Add("");
            Lines.Add($"namespace {Result.Namespace};");
        }

        Lines.Add("");
        Lines.Add($"partial class {Result.ClassName}");
        Lines.Add("{");

        bool IsFirst = true;

        foreach (SceneNodeModel Node in EnumerateDepthFirst(Root))
        {
            if (!IsFirst)
            {
                Lines.Add("");
            }

            IsFirst = false;

            Lines.Add($"    private static partial global::CSharpGameEngine.Entities.SceneNodeSymbol {Node.PropertyName}");
            Lines.Add("    {");
            Lines.Add($"        get => new global::CSharpGameEngine.Entities.SceneNodeSymbol(new global::CSharpGameEngine.Entities.SceneNodeId(0x{Node.NodeId:X16}UL), nameof({Node.PropertyName}));");
            Lines.Add("    }");
        }

        Lines.Add("}");
        Lines.Add("");

        string HintName = Result.Namespace is null
            ? $"{Result.ClassName}.SceneNodes.g.cs"
            : $"{Result.Namespace}.{Result.ClassName}.SceneNodes.g.cs";

        Context.AddSource(HintName, SourceText.From(string.Join("\n", Lines), Encoding.UTF8));
    }

    private static IEnumerable<SceneNodeModel> EnumerateDepthFirst(SceneNodeModel Node)
    {
        yield return Node;

        foreach (SceneNodeModel Child in Node.Children)
        {
            foreach (SceneNodeModel Descendant in EnumerateDepthFirst(Child))
            {
                yield return Descendant;
            }
        }
    }
}
