namespace CSharpGameEngine.CodeAnalysis;

internal static class GameSystemSnapshotEmitter {
    private const string HintName="GameSystem.Snapshot.g.cs";
    internal static void Emit(SourceProductionContext Context,GameSystemRegistry Registry,SnapshotSchemaMap Schemas){
        var Invalid=false;
        foreach(var Component in Registry.ComponentsByIndex){
            if(Schemas.SnapshotRequired&&Schemas.Issue(Component.TypeFullyQualifiedName) is {}Issue){
                Context.ReportDiagnostic(Diagnostic.Create(GameSystemDiagnostics.SnapshotMustBeStatic,Location.None,Component.TypeFullyQualifiedName,Issue));
                Invalid=true;
            }
        }
        if(Invalid){ return; }
        List<string>Lines=[
            "// <auto-generated/>",
            "#nullable enable",
            "namespace CSharpGameEngine.Entities;",
            "public partial struct World {",
        ];
        foreach(var Component in Registry.ComponentsByIndex){
            Lines.Add($"    private static readonly global::CSharpGameEngine.Entities.EcsSnapshotComponentDescriptor SnapshotComponent{Component.Index} = {Schemas.Get(Component.TypeFullyQualifiedName)};");
            if(Schemas.Issue(Component.TypeFullyQualifiedName) is not null){
                var Message=Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral($"Snapshot component {Component.TypeFullyQualifiedName} requires a static value codec.",true);
                Lines.Add($"    private static byte[] SerializeSnapshotComponent{Component.Index}(in {Component.TypeFullyQualifiedName} Value) => throw new global::System.NotSupportedException({Message});");
                Lines.Add($"    private static bool DeserializeSnapshotComponent{Component.Index}(byte[] Payload, out {Component.TypeFullyQualifiedName} Value, out string Error) {{ Value = default; Error = {Message}; return false; }}");
                continue;
            }
            if(Schemas.Writer(Component.TypeFullyQualifiedName) is {}Body){
                Lines.Add($"    private static byte[] SerializeSnapshotComponent{Component.Index}(in {Component.TypeFullyQualifiedName} Value) {{");
                Lines.Add(Body);
                Lines.Add("    }");
            }
            if(Schemas.Reader(Component.TypeFullyQualifiedName) is {}Reader){
                Lines.Add($"    private static bool DeserializeSnapshotComponent{Component.Index}(byte[] Payload, out {Component.TypeFullyQualifiedName} Value, out string Error) {{");
                Lines.Add(Reader.Replace("$SERIALIZE$",$"SerializeSnapshotComponent{Component.Index}"));
                Lines.Add("    }");
            }
        }
        foreach(var Archetype in Registry.Archetypes){
            string Descriptors=string.Join(", ",SortedComponents(Archetype,Registry).Select(static Component=>$"SnapshotComponent{Component.Index}"));
            Lines.Add($"    private static readonly global::CSharpGameEngine.Entities.EcsSnapshotArchetypeDescriptor Snapshot{Archetype.Name} = global::CSharpGameEngine.Entities.EcsSnapshotArchetypeDescriptor.Create({Descriptors});");
        }
        string Archetypes=string.Join(", ",Registry.Archetypes.Select(static Archetype=>$"Snapshot{Archetype.Name}"));
        Lines.Add($"    public static string SnapshotSchemaFingerprint {{ get; }} = global::CSharpGameEngine.Entities.EcsSnapshotSchema.ComputeFingerprint({Archetypes});");
        Lines.AddRange(BuildReadDocument(Registry,Schemas));
        Lines.AddRange(BuildCapture(Registry,Schemas));
        Lines.AddRange(BuildRestore(Registry));
        Lines.AddRange(BuildValidate(Registry,Schemas));
        Lines.AddRange(BuildApply(Registry,Schemas));
        Lines.Add("}");
        Context.AddSource(HintName,SourceText.From(string.Join(((char)10).ToString(),Lines),Encoding.UTF8));
    }
    private static List<string>BuildReadDocument(GameSystemRegistry Registry,SnapshotSchemaMap Schemas){
        var Lines=new List<string>{
            "    private static bool TryReadSnapshotArtifact(global::System.ReadOnlySpan<byte> Artifact, out global::CSharpGameEngine.Entities.EcsSnapshotDocument? Document, out global::CSharpGameEngine.Entities.EcsSnapshotError Error) {",
            "        Document = null;",
            "        if (!global::CSharpGameEngine.Entities.EcsSnapshotArtifactCodec.TryRead(Artifact, SnapshotSchemaFingerprint, out var Source, out Error)) return false;",
            "        try {",
            "            var Original = Source!;",
            "            var Entities = new global::System.Collections.Generic.List<global::CSharpGameEngine.Entities.EcsSnapshotEntityData>(Original.Entities.Count);",
            "            foreach (var Entity in Original.Entities) {",
            "                string? Key = null;",
        };
        foreach(var Archetype in Registry.Archetypes){
            Lines.Add($"                if (Entity.ArchetypeKey == Snapshot{Archetype.Name}.Key) Key = Snapshot{Archetype.Name}.Key;");
        }
        Lines.AddRange([
            "                if (Key is null) { Error = new(global::CSharpGameEngine.Entities.EcsSnapshotErrorCode.ArchetypeMismatch, \"Snapshot archetype has no static schema correspondence.\"); return false; }",
            "                var Components = new global::System.Collections.Generic.List<global::CSharpGameEngine.Entities.EcsSnapshotComponentData>(Entity.Components.Count);",
            "                foreach (var Component in Entity.Components) {",
        ]);
        foreach(var Component in Registry.ComponentsByIndex.Where(Component=>!Schemas.IsTransient(Component.TypeFullyQualifiedName))){
            Lines.Add($"                    if (Component.TypeId == SnapshotComponent{Component.Index}.TypeId) {{");
            Lines.Add($"                        if (!DeserializeSnapshotComponent{Component.Index}(Component.Payload, out var Value{Component.Index}, out var Failure{Component.Index})) {{ Error = new(global::CSharpGameEngine.Entities.EcsSnapshotErrorCode.ComponentMismatch, Failure{Component.Index}); return false; }}");
            Lines.Add($"                        Components.Add(Component with {{ Payload = SerializeSnapshotComponent{Component.Index}(in Value{Component.Index}) }}); continue;");
            Lines.Add("                    }");
        }
        Lines.AddRange([
            "                    Error = new(global::CSharpGameEngine.Entities.EcsSnapshotErrorCode.ComponentMismatch, \"Snapshot component has no static value codec.\"); return false;",
            "                }",
            "                Entities.Add(Entity with { ArchetypeKey = Key, Components = Components.ToArray() });",
            "            }",
            "            Document = global::CSharpGameEngine.Entities.EcsSnapshotArtifactCodec.CreateDocument(SnapshotSchemaFingerprint, Original.Tick, Original.EventHash, Original.CapturedCells, Entities);",
            "            Error = global::CSharpGameEngine.Entities.EcsSnapshotError.None; return true;",
            "        } catch (global::System.Exception Failure) when (Failure is global::System.ArgumentException or global::System.OverflowException or global::System.InvalidOperationException or global::System.Text.Json.JsonException) {",
            "            Error = new(global::CSharpGameEngine.Entities.EcsSnapshotErrorCode.InvalidPayload, Failure.Message); return false;",
            "        }",
            "    }",
        ]);
        return Lines;
    }

    private static List<string>BuildCapture(GameSystemRegistry Registry,SnapshotSchemaMap Schemas){
        if(Registry.Archetypes.IsEmpty){
            return[
                "    public byte[] CaptureSnapshot(ulong Tick, string EventHash) {",
                "        this.CaptureSnapshotState(out var Cells, out var Entities);",
                "        return global::CSharpGameEngine.Entities.EcsSnapshotArtifactCodec.Write(SnapshotSchemaFingerprint, Tick, EventHash, Cells, Entities);",
                "    }",
                "    public byte[] UpdateSnapshot(global::System.ReadOnlySpan<byte> PreviousArtifact, ulong Tick, string EventHash) {",
                "        if (!TryReadSnapshotArtifact(PreviousArtifact, out var Previous, out var Error)) throw new global::System.IO.InvalidDataException(Error.Message);",
                "        this.CaptureSnapshotState(out var Cells, out var Entities);",
                "        return global::CSharpGameEngine.Entities.EcsSnapshotArtifactCodec.Merge(Previous!, SnapshotSchemaFingerprint, Tick, EventHash, Cells, Entities);",
                "    }",
                "    private void CaptureSnapshotState(out global::CSharpGameEngine.Contracts.WorldCellId[] Cells, out global::CSharpGameEngine.Entities.EcsSnapshotEntityData[] Entities) {",
