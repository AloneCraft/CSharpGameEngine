using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace CSharpGameEngine.CodeAnalysis.Tests;

public sealed class GenerateEntityGeneratorEmissionTests
{
    [Theory]
    [InlineData("ObjectOrientedAos")]
    [InlineData("EcsSoa")]
    public void MinimalSource_GeneratesCode_WithNoCompilationErrors(string kindMemberName)
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings(kindMemberName)
            + CharacterSource;

        CSharpCompilation compilation = GenerateEntityGeneratorTestHelper.CreateCompilation(source);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new GenerateEntityGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation outputCompilation, out System.Collections.Immutable.ImmutableArray<Diagnostic> generatorDiagnostics);

        Assert.Empty(generatorDiagnostics);
        Assert.Empty(outputCompilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error));
    }

    [Theory]
    [InlineData("ObjectOrientedAos")]
    [InlineData("EcsSoa")]
    public void HintNames_AreDeterministicAcrossIndependentRuns(string kindMemberName)
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings(kindMemberName)
            + CharacterSource;

        GeneratorDriverRunResult first = GenerateEntityGeneratorTestHelper.RunGenerator(source);
        GeneratorDriverRunResult second = GenerateEntityGeneratorTestHelper.RunGenerator(source);

        string[] firstHintNames = [.. first.Results[0].GeneratedSources.Select(s => s.HintName).OrderBy(n => n, StringComparer.Ordinal)];
        string[] secondHintNames = [.. second.Results[0].GeneratedSources.Select(s => s.HintName).OrderBy(n => n, StringComparer.Ordinal)];

        Assert.Equal(firstHintNames, secondHintNames);

        foreach (string hintName in firstHintNames)
        {
            string firstText = first.Results[0].GeneratedSources.Single(s => s.HintName == hintName).SourceText.ToString();
            string secondText = second.Results[0].GeneratedSources.Single(s => s.HintName == hintName).SourceText.ToString();
            Assert.Equal(firstText, secondText);
        }
    }

    [Theory]
    [InlineData("ObjectOrientedAos")]
    [InlineData("EcsSoa")]
    public void GeneratedSources_ContainAutoGeneratedHeaderAndNullableEnable(string kindMemberName)
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings(kindMemberName)
            + CharacterSource;

        GeneratorDriverRunResult result = GenerateEntityGeneratorTestHelper.RunGenerator(source);

        Assert.Empty(result.Diagnostics);
        Assert.NotEmpty(result.Results[0].GeneratedSources);

        foreach (GeneratedSourceResult generated in result.Results[0].GeneratedSources)
        {
            string text = generated.SourceText.ToString();
            Assert.StartsWith("// <auto-generated/>", text, StringComparison.Ordinal);
            Assert.Contains("#nullable enable", text, StringComparison.Ordinal);
        }
    }

    [Theory]
    [InlineData("ObjectOrientedAos")]
    [InlineData("EcsSoa")]
    public void GeneratedSources_ParseWithoutSyntaxDiagnostics(string kindMemberName)
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings(kindMemberName)
            + CharacterSource;

        GeneratorDriverRunResult result = GenerateEntityGeneratorTestHelper.RunGenerator(source);

        foreach (GeneratedSourceResult generated in result.Results[0].GeneratedSources)
        {
            SyntaxTree reparsed = CSharpSyntaxTree.ParseText(generated.SourceText.ToString(), new CSharpParseOptions(LanguageVersion.Latest));
            Assert.Empty(reparsed.GetDiagnostics());
        }
    }

    [Fact]
    public void DeclarationOrderChanged_NormalizedSignatureStaysTheSame()
    {
        string declaredInOrder = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings("EcsSoa")
            + """


            [GenerateEntity(EntityGenerationSettings.Kind)]
            public partial struct Character
            {
                public partial Health Health { get; set; }
                public partial LocalTransform Transform { get; set; }
                public partial Velocity Velocity { get; set; }
            }
            """;

        string declaredOutOfOrder = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings("EcsSoa")
            + CharacterSource;

        string inOrderCommon = SingleGeneratedSource(declaredInOrder, "Common");
        string outOfOrderCommon = SingleGeneratedSource(declaredOutOfOrder, "Common");

        string inOrderSignature = ExtractSignatureBlock(inOrderCommon);
        string outOfOrderSignature = ExtractSignatureBlock(outOfOrderCommon);

        Assert.Equal(inOrderSignature, outOfOrderSignature);
    }

    [Fact]
    public void StaticAndConstMembers_AreNotMisdetectedAsComponents()
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings("EcsSoa")
            + """


            [GenerateEntity(EntityGenerationSettings.Kind)]
            public partial struct Character
            {
                public const int MaxHealth = 100;

                public static Health DefaultHealth { get; set; }

                public partial LocalTransform Transform { get; set; }
                public partial Velocity Velocity { get; set; }
                public partial Health Health { get; set; }

                public static Character Spawn(CharacterStore store, in CharacterCreateInfo info)
                {
                    return store.Create(in info);
                }
            }
            """;

        GeneratorDriverRunResult result = GenerateEntityGeneratorTestHelper.RunGenerator(source);

        Assert.Empty(result.Diagnostics);
        string commonText = result.Results[0].GeneratedSources.Single(s => s.HintName.EndsWith(".Common.g.cs", StringComparison.Ordinal)).SourceText.ToString();

        Assert.DoesNotContain("MaxHealth", commonText, StringComparison.Ordinal);
        Assert.DoesNotContain("DefaultHealth", commonText, StringComparison.Ordinal);
    }

    [Fact]
    public void NestedGenerateEntityStruct_CompilesWithoutErrors()
    {
        string source = GenerateEntityGeneratorTestHelper.CommonComponents
            + GenerateEntityGeneratorTestHelper.EntityGenerationSettings("EcsSoa")
            + """


            public partial class Container
            {
                [GenerateEntity(EntityGenerationSettings.Kind)]
                public partial struct Character
                {
                    public partial LocalTransform Transform { get; set; }
                    public partial Velocity Velocity { get; set; }
                }
            }
            """;

        CSharpCompilation compilation = GenerateEntityGeneratorTestHelper.CreateCompilation(source);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new GenerateEntityGenerator());
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation outputCompilation, out System.Collections.Immutable.ImmutableArray<Diagnostic> generatorDiagnostics);

        Assert.Empty(generatorDiagnostics);
        Assert.Empty(outputCompilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error));
    }

    private const string CharacterSource = """


        [GenerateEntity(EntityGenerationSettings.Kind)]
        public partial struct Character
        {
            // わざと正規化順とは異なる順番で書いている
            public partial LocalTransform Transform { get; set; }
            public partial Velocity Velocity { get; set; }
            public partial Health Health { get; set; }
        }
        """;

    private static string SingleGeneratedSource(string source, string suffix)
    {
        GeneratorDriverRunResult result = GenerateEntityGeneratorTestHelper.RunGenerator(source);
        Assert.Empty(result.Diagnostics);
        return result.Results[0].GeneratedSources.Single(s => s.HintName.EndsWith($".{suffix}.g.cs", StringComparison.Ordinal)).SourceText.ToString();
    }

    private static string ExtractSignatureBlock(string commonSourceText)
    {
        int start = commonSourceText.IndexOf("normalizedSignatureBacking", StringComparison.Ordinal);
        int end = commonSourceText.IndexOf("};", start, StringComparison.Ordinal);
        return commonSourceText.Substring(start, end - start);
    }
}
